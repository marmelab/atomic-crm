    -- Client + Session Operations cadence correction: same "Task points AT
    -- its context" pattern as sales_call_id above — a
    -- resolve_client_session_cadence Task's only real subject is one
    -- specific client_session_cadence_issues row (an Enrollment can have
    -- more than one unresolved week at once).
    cadence_issue_id bigint,
    constraint tasks_status_check check (status in ('pending', 'waiting', 'completed', 'cancelled'))
);

