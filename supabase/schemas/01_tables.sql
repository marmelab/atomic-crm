    -- set_task_enrollment_id_consistency() below): this Task is about one
    -- specific checklist item.
    onboarding_item_id bigint,
    -- Client Offboarding slice: the offboarding mirror of
    -- onboarding_item_id above — same "points AT its context" pattern,
    -- same consistency enforcement, never set together with
