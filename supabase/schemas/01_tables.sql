-- A persistent product/program definition. Offers are few and change rarely
-- (Leif has exactly two today), so this is deliberately a flat table rather
-- than a versioned catalog — historical pricing integrity for Opportunities
-- already sold comes from the snapshot columns on `deals`, not from this row.
create table public.offers (
    id bigint generated by default as identity primary key,
    name text not null,
    type text not null,
    duration text not null,
    current_price numeric(10, 2) not null,
    -- Scholarship Pricing + Capacity slice: the locked, admin-editable
    -- scholarship total for this Offer (mirrors current_price exactly —
    -- live/authoritative, never itself historically authoritative for an
    -- already-sold Opportunity). Null means this Offer has no scholarship
    -- pricing configured; deals.pricing_mode can only be set to
    -- 'scholarship' when this is set (see handle_deal_saved()).
    scholarship_price numeric(10, 2),
    -- Only meaningful for individual offers (e.g. The Living Example caps
    -- concurrent active clients). Group offers manage capacity per-Cohort
    -- instead, so this stays null for them.
    max_active_clients smallint,
    is_active boolean not null default true,
    -- Acuity/Sales Call Lifecycle slice: durable mapping to the Acuity
    -- appointment type whose bookings are this Offer's sales calls. For an
    -- individual Offer this is the only level a mapping can live at. A
    -- group Offer may ALSO carry one here (GYU real-infrastructure slice,
    -- sealing pass): the correct, durable home for one canonical
    -- appointment type meant to serve every Cohort of that Offer (e.g.
    -- GYU's real "Let's Meet" type — one calendar for all rounds, not one
    -- per Cohort). A specific Cohort can still override with its own
    -- mapping when a round genuinely needs a separate appointment type/
    -- calendar — see cohorts.acuity_appointment_type_id below; a Cohort-
    -- level mapping is checked second and takes precedence for its own
    -- Cohort. See sales-calls/offerCohortAcuityMapping.ts's own resolver
    -- comment for the full matching rationale (why an Offer-level match on
    -- a group Offer never needs to also identify a specific Cohort here).
    -- Stable ID, never a display-name match.
    acuity_appointment_type_id text,
    -- Client + Session Operations slice: a SEPARATE durable mapping from
    -- the one above — that column identifies this Offer's SALES CALL
    -- appointment type (a prospect deciding whether to buy); this one
    -- identifies the PAID CLIENT SESSION appointment type (an already-
    -- enrolled client's recurring 1:1, e.g. The Living Example's real
    -- "Zoom 1:1", 90522599). Structurally distinct columns/resolvers so a
    -- paid-client booking can never enter sales_call logic (and vice
    -- versa) merely because they happen to share a Contact/Offer. Only
    -- meaningful for an individual Offer in this slice (client-session
    -- attendance for a group Offer's cohort sessions is explicitly out of
    -- scope) — see sessions/clientSessionAcuityMapping.ts.
    client_session_acuity_appointment_type_id text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint offers_type_check check (type in ('individual', 'group'))
);

