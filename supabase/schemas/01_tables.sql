-- Client + Session Operations cadence correction: the read-only ingestion
-- of Leif's real working calendar (Google Calendar, "Year Planning" —
-- see sync_year_planning_calendar's own header comment for why this is
-- the authoritative source of expected 1:1 weeks instead of a hardcoded
-- "3 arbitrary weeks per month" assumption). One row per real calendar
-- event whose title marks it as an open-for-1:1s window; never written by
-- the CRM back to the calendar (read-only ingestion only).
create table public.expected_session_windows (
    id bigint generated by default as identity primary key,
    -- Which Offer's cadence this window applies to (only The Living
    -- Example has client_session_acuity_appointment_type_id set today —
    -- see offers table above — but this stays a real FK rather than an
    -- assumed singleton so a second individual offer could opt in later
    -- without a schema change).
    offer_id bigint not null,
    -- The source Google Calendar's own id (an email-shaped string) and
    -- this event's own id within it — both stable identifiers from the
    -- calendar API, never a display-name/title match for identity (title
    -- is only ever used to decide whether an event COUNTS as a window in
    -- the first place — see sync_year_planning_calendar's own matching
    -- comment for the real observed title variance: "1:1s", "1:1 week",
    -- "1:1", "1:1s add").
    external_calendar_id text not null,
    external_event_id text not null,
    -- The event's own original title, kept verbatim for audit/debugging —
    -- never re-derived or re-matched against after ingestion.
    raw_title text not null,
    -- Google Calendar's own all-day-event semantics: date-only (not
    -- timestamptz — these are calendar dates, not moments in time, same
    -- convention as cohorts' program_start_at/program_end_at above), and
    -- window_end is EXCLUSIVE (a Sep 13–17 all-day event covers Sep
    -- 13/14/15/16, never the 17th itself) — never reinterpreted as
    -- inclusive anywhere a window is compared against a session's
    -- scheduled_at.
    window_start date not null,
    window_end date not null,
    -- Soft-delete: the event disappeared from a later sync pass (Leif
    -- deleted/moved it in Google Calendar). Never hard-deleted — an
    -- already-created client_session_cadence_issues row may still
    -- reference this window, and that row's own history must survive the
    -- source event vanishing out from under it.
    deleted_at timestamp with time zone,
    -- Refreshed on every sync pass that still finds this event present —
    -- what actually detects a deletion (present in a previous sync, absent
    -- from the current one) rather than a TTL guess.
    synced_at timestamp with time zone not null default now(),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint expected_session_windows_window_check check (window_end > window_start)
);

-- Idempotent upsert target for sync_year_planning_calendar — a duplicate
-- sync run (retry, overlapping schedule) always resolves to the SAME row
-- by (calendar, event id), never a second one.
create unique index expected_session_windows_external_event_idx on public.expected_session_windows (external_calendar_id, external_event_id);

