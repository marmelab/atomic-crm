    unique (enrollment_id, requirement_key)
);

-- A person waiting for space/timing in a program, independent of the
-- active sales pipeline (Waitlists slice, §1): "does this person want
-- access when appropriate" rather than "are they currently moving through
-- a sales decision". Deliberately its own entity — not a boolean on
-- contacts (a person can wait for more than one Offer/Cohort over their
-- lifetime) and not an Opportunity stage (waiting and actively deciding
-- are different relationships that can coexist or diverge).
create table public.waitlist_entries (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    offer_id bigint not null,
    -- Only set for a cohort-specific entry, and only to a Cohort belonging
    -- to that same offer (enforced by handle_waitlist_entry_saved()) — an
    -- offer-level entry (e.g. "wants GYU generally") leaves this null.
    cohort_id bigint,
    status text not null default 'waiting',
    joined_at timestamp with time zone not null default now(),
    desired_timing text,
    notes text,
    -- Leif's manual ordering signal, not a strict FIFO queue — nullable
    -- and purely advisory (Waitlists slice, §14).
    priority smallint,
    source text,
    invited_at timestamp with time zone,
    converted_at timestamp with time zone,
    -- The Opportunity this entry became, once converted — lets the Contact
    -- page and this entry both link straight to it (§12).
    converted_opportunity_id bigint,
    removed_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint waitlist_entries_status_check check (status in ('waiting', 'invited', 'converted', 'removed')),
    constraint waitlist_entries_source_check check (source in ('instagram', 'referral', 'podcast', 'workshop', 'substack', 'google', 'other'))
);

-- Prevents duplicate ACTIVE (waiting/invited) entries for the same
-- Contact + Offer + Cohort (§4) at the database level — the primary
-- enforcement is the shared domain check in
-- waitlist/waitlistEntryValidation.ts (the only thing that can behave
-- identically in FakeRest, which has no constraint engine at all), this
-- index is defense-in-depth against races/direct SQL on the real DB.
-- Historical converted/removed entries are excluded, so rejoining later is
-- always allowed. cohort_id is coalesced to -1 (never a valid id) because
-- Postgres treats each NULL as distinct in a plain unique index, which
-- would otherwise let two offer-level (cohort_id null) entries collide
-- silently past this constraint.
create unique index waitlist_entries_active_unique_idx on public.waitlist_entries (contact_id, offer_id, coalesce(cohort_id, -1)) where (status in ('waiting', 'invited'));

-- The durable current-state record for a sales call/appointment (Acuity/
-- Sales Call Lifecycle slice), one row per LOGICAL appointment — a
-- reschedule updates this row rather than creating a second one, so it
-- can never look like two independent calls in later conversion
-- analytics. Individual lifecycle facts (booked/rescheduled/cancelled/
-- attendance recorded, with occurred_at and old/new values) are preserved
-- separately in sales_call_events; this row is only ever current/summary
-- state.
create table public.sales_calls (
    id bigint generated by default as identity primary key,
    -- Nullable: a booking that can't be safely matched to exactly one
    -- active Opportunity is preserved with opportunity_id = null rather
    -- than guessed — see sales-calls/matchAcuityBooking.ts. Surfaced via
    -- a "Resolve Sales Call" task rather than silently buried.
    opportunity_id bigint,
    -- Always resolved (normalized-email match-or-create, Native
    -- Application Intake's own matching principle) even when the
    -- Opportunity is ambiguous.
    contact_id bigint not null,
    status text not null default 'booked',
    -- Set once at creation, never updated by a reschedule.
    original_scheduled_at timestamp with time zone not null,
    -- The current/latest scheduled time. Mirrored onto the owning
    -- Opportunity's sales_call_at (a denormalized convenience field, kept
    -- exactly as it already was) by sync_deal_sales_call_at() below.
    scheduled_at timestamp with time zone not null,
    reschedule_count smallint not null default 0,
    last_rescheduled_at timestamp with time zone,
    cancelled_at timestamp with time zone,
    -- Always a human/CRM action (Complete Sales Call), never inferred
    -- from Acuity — an appointment's time passing does not prove
    -- attendance.
    attendance text,
    attendance_recorded_at timestamp with time zone,
    source text not null default 'manual',
    acuity_appointment_id text,
    acuity_appointment_type_id text,
    -- Unmatched Sales Call Resolution slice: distinct from
    -- opportunity_id — a booking can be unresolved (both null), matched
    -- (opportunity_id set), or deliberately dismissed (dismissed_at set,
    -- opportunity_id stays null forever). Never overload
    -- opportunity_id = null to mean both "not yet resolved" and
    -- "resolved as not-a-sales-situation" — a duplicate Acuity webhook
    -- replay needs to tell those apart to never resurrect a dismissed
    -- booking's alert.
    dismissed_at timestamp with time zone,
    dismissal_reason text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint sales_calls_status_check check (status in ('booked', 'cancelled')),
    constraint sales_calls_attendance_check check (attendance in ('attended', 'no_show')),
    constraint sales_calls_source_check check (source in ('acuity', 'manual'))
);

-- Defense-in-depth alongside the domain-layer duplicate-booking check
-- (sales-calls/bookSalesCall.ts): at most one currently-booked call per
-- Opportunity — a second incoming booking for the same Opportunity is a
-- reschedule of the existing row, never a second one.
create unique index sales_calls_one_booked_per_opportunity_idx on public.sales_calls (opportunity_id) where (status = 'booked' and opportunity_id is not null);
create unique index sales_calls_acuity_appointment_id_idx on public.sales_calls (acuity_appointment_id) where (acuity_appointment_id is not null);

-- Append-only lifecycle history for a sales_calls row (Leif's own decision:
-- durable individual events, not just a reschedule_count + last_rescheduled_at
-- summary). Deliberately NOT a generalized event-sourcing log — sales_calls
-- stays the easy current-state record every read goes through; this table
-- exists only so multiple reschedules don't collapse into a single count.
create table public.sales_call_events (
    id bigint generated by default as identity primary key,
    sales_call_id bigint not null,
    kind text not null,
    occurred_at timestamp with time zone not null default now(),
    -- Only set for kind = 'rescheduled'.
    previous_scheduled_at timestamp with time zone,
    new_scheduled_at timestamp with time zone,
    -- Only set for kind = 'attendance_recorded'.
    attendance text,
    -- Only set for kind = 'dismissed' (Unmatched Sales Call Resolution
    -- slice) — mirrored from sales_calls.dismissal_reason at the moment
    -- of dismissal, same "final state also durable in its own event"
    -- convention as attendance above.
    dismissal_reason text,
    created_at timestamp with time zone not null default now(),
    constraint sales_call_events_kind_check check (kind in ('booked', 'rescheduled', 'cancelled', 'attendance_recorded', 'opportunity_attached', 'dismissed')),
    constraint sales_call_events_attendance_check check (attendance in ('attended', 'no_show'))
);

