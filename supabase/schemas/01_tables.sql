-- A persistent product/program definition. Offers are few and change rarely
-- (Leif has exactly two today), so this is deliberately a flat table rather
-- than a versioned catalog — historical pricing integrity for Opportunities
-- already sold comes from the snapshot columns on `deals`, not from this row.
create table public.offers (
    id bigint generated by default as identity primary key,
    name text not null,
    type text not null,
    duration text not null,
    current_price numeric(10, 2) not null,
    -- Only meaningful for individual offers (e.g. The Living Example caps
    -- concurrent active clients). Group offers manage capacity per-Cohort
    -- instead, so this stays null for them.
    max_active_clients smallint,
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint offers_type_check check (type in ('individual', 'group'))
);

-- Queryable, structured payment plans for an Offer (not a prose blob), so a
-- future Stripe Checkout/payment-plan generator has real rows to read.
create table public.offer_payment_options (
    id bigint generated by default as identity primary key,
    offer_id bigint not null,
    name text not null,
    total numeric(10, 2) not null,
    installments smallint not null,
    installment_amount numeric(10, 2) not null,
    -- Some options (e.g. "Financial Need") are authorized case-by-case, not
    -- surfaced to every prospect by default.
    is_public boolean not null default true,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);

-- A single round of a GROUP offer (e.g. a Growing Yourself Up cohort).
-- Individual offers (The Living Example) never use Cohorts.
create table public.cohorts (
    id bigint generated by default as identity primary key,
    offer_id bigint not null,
    name text not null,
    status text not null default 'draft',
    -- Date-only (not timestamptz): these are calendar dates, not moments in
    -- time, and <DateField>'s UTC-safe rendering only kicks in for bare
    -- "YYYY-MM-DD" values (see date-field.tsx).
    applications_open_at date,
    applications_close_at date,
    program_start_at date,
    program_end_at date,
    minimum_capacity smallint,
    target_capacity smallint,
    maximum_capacity smallint,
    -- Future integration identifiers (not wired up in this slice).
    slack_channel_id text,
    calendar_id text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint cohorts_status_check check (status in ('draft', 'applications_open', 'applications_closed', 'active', 'completed'))
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_id bigint,
    category text,
    offer_id bigint not null,
    -- Only set when offer_id points to a GROUP offer, and only to a Cohort
    -- belonging to that same offer (enforced by handle_deal_saved()).
    cohort_id bigint,
    stage text not null,
    -- Exit/outcome, separate from stage: an active opportunity has no outcome.
    outcome text,
    owner_decision text,
    -- Only meaningful when owner_decision = 'would_work_with'.
    prospect_decision text,
    -- Shown when prospect_decision = 'thinking'; defaults to +4 days in the UI.
    follow_up_date date,
    -- Next scheduled sales call, if any. One piece of the future "Next Up"
    -- surface alongside follow_up_date and Enrollment/Cohort dates.
    sales_call_at timestamp with time zone,
    source text,
    entry_path text,
    description text,
    amount bigint,
    -- Commercial snapshot, captured at save time by handle_deal_saved() so a
    -- later change to the Offer/payment option never rewrites historical
    -- sales context on an existing Opportunity.
    offer_name_snapshot text,
    offer_price_snapshot numeric(10, 2),
    selected_payment_option_id bigint,
    selected_payment_total numeric(10, 2),
    selected_installment_count smallint,
    selected_installment_amount numeric(10, 2),
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint,
    constraint deals_outcome_check check (outcome in ('nurture', 'needs_higher_care', 'not_fit', 'lost')),
    constraint deals_owner_decision_check check (owner_decision in ('would_work_with', 'workshops_only', 'do_not_engage')),
    constraint deals_prospect_decision_check check (prospect_decision in ('yes', 'thinking', 'no')),
    constraint deals_source_check check (source in ('instagram', 'referral', 'podcast', 'workshop', 'substack', 'google', 'other')),
    constraint deals_entry_path_check check (entry_path in ('instagram_conversation', 'sales_page', 'other'))
);

-- A submitted program/coaching application. Reached only through its
-- Opportunity (Contact/Offer/Cohort are all reachable that way), so no extra
-- FKs are duplicated here.
create table public.applications (
    id bigint generated by default as identity primary key,
    opportunity_id bigint not null,
    -- Review outcomes are distinct on purpose (Native Applications slice,
    -- §1): 'approved' means "qualified for a sales call", not "Leif wants
    -- to work with them" — that call still happens later. The generic
    -- 'rejected' value is retired in favor of the specific reason.
    status text not null default 'pending',
    submitted_at timestamp with time zone not null default now(),
    reviewed_at timestamp with time zone,
    -- Application questions differ by Offer and will evolve; jsonb avoids a
    -- migration every time the question set changes. No fixed schema yet.
    raw_answers jsonb not null default '{}'::jsonb,
    -- Free text for now; shaped to hold a future AI-generated summary.
    summary text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint applications_status_check check (status in ('pending', 'approved', 'needs_higher_care', 'not_fit', 'do_not_engage'))
);

-- The commercial/client lifecycle after a successful sale. At most one per
-- Opportunity (enforced by the unique index below), which is also what makes
-- handle_deal_saved()'s Won -> Enrollment creation idempotent.
create table public.enrollments (
    id bigint generated by default as identity primary key,
    opportunity_id bigint not null,
    status text not null default 'onboarding',
    start_date date,
    end_date date,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint enrollments_status_check check (status in ('onboarding', 'active', 'offboarding', 'completed'))
);

-- A person waiting for space/timing in a program, independent of the
-- active sales pipeline (Waitlists slice, §1): "does this person want
-- access when appropriate" rather than "are they currently moving through
-- a sales decision". Deliberately its own entity — not a boolean on
-- contacts (a person can wait for more than one Offer/Cohort over their
-- lifetime) and not an Opportunity stage (waiting and actively deciding
-- are different relationships that can coexist or diverge).
create table public.waitlist_entries (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    offer_id bigint not null,
    -- Only set for a cohort-specific entry, and only to a Cohort belonging
    -- to that same offer (enforced by handle_waitlist_entry_saved()) — an
    -- offer-level entry (e.g. "wants GYU generally") leaves this null.
    cohort_id bigint,
    status text not null default 'waiting',
    joined_at timestamp with time zone not null default now(),
    desired_timing text,
    notes text,
    -- Leif's manual ordering signal, not a strict FIFO queue — nullable
    -- and purely advisory (Waitlists slice, §14).
    priority smallint,
    source text,
    invited_at timestamp with time zone,
    converted_at timestamp with time zone,
    -- The Opportunity this entry became, once converted — lets the Contact
    -- page and this entry both link straight to it (§12).
    converted_opportunity_id bigint,
    removed_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint waitlist_entries_status_check check (status in ('waiting', 'invited', 'converted', 'removed')),
    constraint waitlist_entries_source_check check (source in ('instagram', 'referral', 'podcast', 'workshop', 'substack', 'google', 'other'))
);

-- Prevents duplicate ACTIVE (waiting/invited) entries for the same
-- Contact + Offer + Cohort (§4) at the database level — the primary
-- enforcement is the shared domain check in
-- waitlist/waitlistEntryValidation.ts (the only thing that can behave
-- identically in FakeRest, which has no constraint engine at all), this
-- index is defense-in-depth against races/direct SQL on the real DB.
-- Historical converted/removed entries are excluded, so rejoining later is
-- always allowed. cohort_id is coalesced to -1 (never a valid id) because
-- Postgres treats each NULL as distinct in a plain unique index, which
-- would otherwise let two offer-level (cohort_id null) entries collide
-- silently past this constraint.
create unique index waitlist_entries_active_unique_idx on public.waitlist_entries (contact_id, offer_id, coalesce(cohort_id, -1)) where (status in ('waiting', 'invited'));

