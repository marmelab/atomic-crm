create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    -- Tasks are reminders/actions, not sales-status controls: this never
    -- reads from or writes to Opportunity/Application state. Kept in sync
    -- with done_date by the app (Pending <-> Completed via the checkbox);
    -- Waiting/Cancelled are set explicitly. ONE deliberate, narrow
    -- exception (Contracts + Onboarding slice): a Task pointing at
    -- onboarding_item_id below IS synced with that one Enrollment
    -- checklist item's status (see sync_onboarding_item_from_task() in
    -- 02_functions.sql) — the checklist is still the durable source of
    -- truth (a cancelled Task never completes its item), this is just
    -- the one direction where completing the Task legitimately means the
    -- work got done.
    status text not null default 'pending',
    sales_id bigint,
    -- Contracts + Onboarding slice: Task points AT its business context
    -- (chosen over the reverse — a context row pointing at its Task —
    -- specifically so a Task can exist for an Enrollment with no specific
    -- checklist item, so one item can later have more than one Task, and
    -- so there is never a stored "current task" pointer elsewhere that
    -- must be kept in sync by hand). Both nullable: most Tasks (sales_call,
    -- follow_up, etc.) still resolve via the existing contact_id heuristic
    -- in useTaskActionDestination.ts, untouched by this slice.
    -- enrollment_id alone: an Enrollment-level Task with no specific
    -- checklist item (e.g. "check in on how onboarding is going").
    enrollment_id bigint,
    -- Set together with enrollment_id (never alone — enforced by
    -- set_task_enrollment_id_consistency() below): this Task is about one
    -- specific checklist item.
    onboarding_item_id bigint,
    -- Unmatched Sales Call Resolution slice: the same "Task points AT its
    -- context" pattern as enrollment_id/onboarding_item_id above — a
    -- resolve_sales_call Task's only real subject is one specific
    -- sales_calls row, never a whole Contact (a returning Contact could
    -- have more than one unresolved booking at once). Independent of
    -- enrollment_id/onboarding_item_id — a Task is never about both an
    -- Enrollment and a Sales Call.
    sales_call_id bigint,
    constraint tasks_status_check check (status in ('pending', 'waiting', 'completed', 'cancelled'))
);

