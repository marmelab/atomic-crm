-- Extensions
create extension if not exists "http" with schema "extensions";
create extension if not exists "citext" with schema "extensions";
-- Created by migration 20260128165057; declared so diffs do not drop it.
create extension if not exists "pgjwt" with schema "extensions";

-- Private schema (used by sales policies migration)
create schema if not exists "private";

create table public.companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb,
    lead_date date default current_date,
    email text,
    whatsapp_number text,
    pitch_point text,
    priority text default 'medium'
        check (priority is null or priority in ('high', 'medium', 'low'))
);

create table public.contacts (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamp with time zone,
    last_seen timestamp with time zone,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint,
    sales_id bigint,
    linkedin_url text,
    email_jsonb jsonb,
    phone_jsonb jsonb,
    whatsapp_number text,
    is_primary boolean not null default false,
    -- Lead lifecycle (null lead_stage = an ordinary contact, not a calling lead)
    lead_stage text,
    retry_count integer not null default 0,
    last_attempt_at timestamp with time zone,
    next_attempt_at timestamp with time zone,
    last_outcome text,
    recycled_at timestamp with time zone,
    recycle_reason text,
    assigned_to bigint,
    assigned_at timestamp with time zone,
    import_batch_id bigint,
    phone_e164 text,
    do_not_contact boolean not null default false,
    constraint contacts_lead_stage_check check (lead_stage in ('new', 'queued', 'in_progress', 'interested', 'recycled', 'not_interested')),
    constraint contacts_last_outcome_check check (last_outcome in ('interested', 'callback', 'no_answer', 'not_interested'))
);

create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[]
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_ids bigint[],
    categories text[],
    stage text not null,
    description text,
    amount bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[]
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    administrator boolean not null,
    user_id uuid not null,
    avatar jsonb,
    disabled boolean not null default false,
    secondary_emails jsonb not null default '[]'::jsonb,
    role text not null default 'bde',
    constraint sales_role_check check (role in ('admin', 'manager', 'bde')),
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    sales_id bigint,
    created_at timestamp with time zone not null default now()
);

create table public.configuration (
    id integer not null default 1 primary key,
    config jsonb not null default '{}'::jsonb,
    constraint configuration_singleton check (id = 1)
);

create table public.brochures (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    company_id bigint,
    contact_id bigint,
    deal_id bigint,
    title text,
    brochure_url text,
    status text not null default 'pending',
    constraint brochures_status_check check (status in ('pending', 'approved', 'not_approved'))
);

create table public.import_batches (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    created_by bigint,
    file_name text,
    total_rows integer not null default 0,
    created_count integer not null default 0,
    duplicate_count integer not null default 0,
    invalid_count integer not null default 0
);

create table public.company_sectors (
    id uuid primary key default gen_random_uuid(),
    value text not null,
    label text not null,
    created_at timestamp with time zone not null default now()
);

create unique index company_sectors_value_key on public.company_sectors using btree (value);
create unique index company_sectors_label_lower_idx on public.company_sectors using btree (lower(label));

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

create table public.user_invitations (
    user_id uuid primary key
);

