-- Contracts + Onboarding slice: the offer-specific onboarding requirement
-- catalog — few rows, changes rarely (same profile as offer_payment_options
-- above), so this is deliberately a plain admin-less config table, managed
-- via migration rather than a UI, not a versioned/UI-editable catalog.
-- Historical integrity for an already-created Enrollment's own checklist
-- comes from enrollment_onboarding_items snapshotting these values at
-- creation time, never from a live join back to this table — editing or
-- deactivating a template row here must never rewrite an existing
-- Enrollment's own history.
create table public.onboarding_requirement_templates (
    id bigint generated by default as identity primary key,
    offer_id bigint not null,
    -- Stable slug (e.g. 'contract', 'slack_access') — the durable identity
    -- an enrollment_onboarding_items row copies forward, never a display
    -- label match.
    key text not null,
    -- Describes the COMPLETED state ("Contract signed"), not the action
    -- ("Send contract") — the Task created from this (see handle_deal_won()
    -- below) carries the action wording separately. Keeps the checklist
    -- readable as durable fulfillment state.
    label text not null,
    -- The Task's own text when this requirement auto-creates one (only for
    -- required items — see handle_deal_won() below) — the ACTION wording
    -- ("Send contract to {name}", "Invite {name} to GYU Slack"), read once
    -- at seed time and rendered into the Task's own permanent `text`; never
    -- re-read afterward, so a later edit here only affects future
    -- Enrollments, same as label/is_required.
    task_text_template text not null,
    is_required boolean not null default true,
    sort_order smallint not null default 0,
    -- Retire a requirement without deleting it (and without touching any
    -- Enrollment that already snapshotted it) — mirrors offers.is_active.
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    unique (offer_id, key)
);

-- Client Offboarding slice: the offboarding mirror of
