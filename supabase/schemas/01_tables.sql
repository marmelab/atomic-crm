-- Historical Migration slice: durable provenance + idempotency for the
-- one-time controlled historical-data import (pre-CRM Notion/Acuity/Stripe
-- history). One row per (table, row) actually written by the historical
-- importer — never touched by ordinary live CRM activity, never read by the
-- application. Answers two needs with one small table, deliberately NOT
-- columns bolted onto contacts/deals/applications/waitlist_entries (a
-- smaller footprint on sealed tables than that would have been):
--   1. Idempotency: entity_table+source_key is unique, so re-running the
--      same historical batch is a safe no-op even where the target table
--      itself has no natural key for this data (most Pipeline/Waitlist-only
--      Contacts have neither a stripe_customer_id nor an
--      acuity_appointment_id to key off of). Deliberately NOT plain
--      `insert ... on conflict (entity_table, source_key) do nothing` in the
--      importer, though — that alone cannot tell "already imported, safe
--      no-op" apart from "this source_key is being asked to point at a
--      DIFFERENT entity_id than before", which would otherwise be silently
--      swallowed. The importer must SELECT the existing row for
--      (entity_table, source_key) first and compare entity_id explicitly,
--      raising a real conflict rather than proceeding, if it differs.
--   2. Auditability: entity_table+entity_id lets anyone later ask "did this
--      Contact/Deal/... come from the 2026 historical migration, or did it
--      happen live in the CRM?" — and source_system/operation answer which
--      source system it came from and whether this row was a fresh create
--      or an enrichment of an existing legitimate record — durable,
--      queryable, six months from now.
-- RLS is enabled with zero policies (see 05_policies.sql): nothing here is
-- ever meant to be reached through PostgREST/anon/authenticated at all;
-- only a service_role connection (which bypasses RLS) ever touches it,
-- exactly the same trust boundary set_historical_migration_mode() relies on.
create table public.historical_import_records (
    id bigint generated by default as identity primary key,
    -- e.g. 'contacts', 'deals', 'applications', 'waitlist_entries',
    -- 'enrollments' — whatever table the importer actually wrote a row into.
    entity_table text not null,
    entity_id bigint not null,
    -- Deterministic key the importer computed BEFORE writing (normalized
    -- email for a Contact, "<contact_source_key>:<offer_id>" for a Deal,
    -- etc.) — never derived from the entity's own generated id, so it is
    -- known and reusable on a retry before the row even exists.
    source_key text not null,
    -- The dominant/qualifying source for this specific entity — a Contact
    -- reconciled from Pipeline+Acuity+Stripe still gets exactly one row
    -- here (one per entity, by the unique constraint below); this records
    -- which source justified creating/updating it, not every source that
    -- happened to corroborate it. Full per-source corroboration detail
    -- lives in the frozen staging manifest, not duplicated into the DB.
    source_system text not null,
    -- Whether the importer created a new row or enriched an existing
    -- legitimate one (the 11 already-real CRM contacts, notably).
    operation text not null,
    -- Free-form batch label, e.g. 'phase3-2026-09' — lets a specific run be
    -- identified/queried without needing a separate batches table.
    batch_id text not null,
    -- Phase 4P: field-level evidence/confidence note for values this
    -- migration had to supply but could not establish exactly — notably
    -- deals.stage_entered_at, which is NOT NULL and drives live Kanban
    -- ordering, so "unknown" cannot be represented as NULL. Records the
    -- evidence class (EXACT_STAGE_EVIDENCE / CREATION_IS_STAGE_ENTRY /
    -- APPROXIMATE_SOURCE_TIMESTAMP) so an approximate anchor is never
    -- silently read back as an exact known transition time.
    evidence_notes text,
    imported_at timestamp with time zone not null default now(),
    constraint historical_import_records_entity_unique unique (entity_table, entity_id),
    constraint historical_import_records_source_unique unique (entity_table, source_key),
    -- 'notion_application' added in Phase 4G: the two ORIGINAL Notion
    -- application databases (LE "1:1 Questionnaire", GYU "Growing Yourself
    -- Up App") are a genuinely distinct source from 'notion_pipeline' (the
    -- downstream Leads & Clients Pipeline) — an Application's provenance
    -- must say which original application record it came from, never the
    -- downstream Pipeline row that merely referenced it via a boolean.
    constraint historical_import_records_source_system_check check (source_system in ('notion_pipeline', 'notion_waitlist', 'notion_application', 'acuity', 'stripe', 'existing_crm')),
    constraint historical_import_records_operation_check check (operation in ('create', 'update'))
);
create index historical_import_records_batch_id_idx on public.historical_import_records using btree (batch_id);
