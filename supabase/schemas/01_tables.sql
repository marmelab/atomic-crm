-- A submitted program/coaching application. Reached only through its
-- Opportunity (Contact/Offer/Cohort are all reachable that way), so no extra
-- FKs are duplicated here.
create table public.applications (
    id bigint generated by default as identity primary key,
    -- CANONICAL PERSON RELATIONSHIP (Gate A final candidate). An
    -- Application belongs to a Contact; it may ALSO reference a sales
    -- Opportunity, but it does not require one. Before this column the
    -- only route from an Application to a person was
    -- opportunity_id -> deals.contact_id, so a legitimate applicant who
    -- never became an Opportunity was stored but unreachable — 88 of 159
    -- real historical Applications, invisible in the CRM. Fabricating
    -- Deals to make them reachable would have falsified sales history.
    contact_id bigint not null,
    -- Record ORIGIN, following the same convention as sales_calls.source /
    -- client_sessions.source. This is the durable distinction between a
    -- live submission that represents outstanding work and an imported
    -- historical record that represents what already happened. It exists
    -- because `status` alone cannot carry it: a historical row must keep
    -- its true status ('pending', 'approved', ...) without that status
    -- creating present-day review work. historical_import_records cannot
    -- serve this purpose — it is deliberately revoked from anon and
    -- authenticated (see 06_grants.sql), so no UI read path can consult it.
    source text not null default 'public_form',
    -- Phase 4H proposal, ACTUALLY APPLIED in Phase 4O (real Postgres
    -- rejected the first Gate A batch of Contact+Application-only
    -- historical rows on exactly this NOT NULL, proving the earlier
    -- comment-only proposal was never wired into SQL): a legitimate
    -- historical applicant who never became a sales Opportunity (Contact +
    -- Application only — no Deal exists to point at) cannot be represented
    -- without either fabricating a Deal (forbidden) or violating this
    -- column. The FK itself is unchanged — a null value simply has no
    -- referent. Confirmed low-blast-radius: useApplicationsGrouped.ts
    -- already treats "no matching deal" as "omit from this Offer/Cohort-
    -- grouped page" rather than crashing, so the only real UI implication
    -- is that a Deal-less historical Application won't appear on the main
    -- Applications page (it still exists and is queryable) — a real,
    -- disclosed limitation, not a crash risk.
    opportunity_id bigint,
    -- Phase 4I finding, NOT YET applied: Application/Offer/Cohort-intent
    -- and Deal/Enrollment cohort are RELATED BUT DISTINCT facts (Leif's
    -- explicit architecture ruling) — an Application must be able to say
    -- what it was FOR without requiring a Deal to exist at all, and
    -- without conflating "what the applicant intended at submission time"
    -- with "what actually happened downstream" (those can legitimately
    -- diverge: a source record can say one cohort while Leif's ruling
    -- says another — both facts are preserved, never overwritten).
    --
    -- offer_id: which Offer this Application was submitted for. Nullable
    -- FOR NOW (existing rows predate this column and have no value to
    -- backfill from except their own Deal, which the historical importer
    -- deliberately does NOT always create) — intended to tighten to NOT
    -- NULL once backfilled (every existing live row can be backfilled
    -- deterministically from opportunity_id -> deals.offer_id; see this
    -- table's own migration file for the exact backfill statement). The
    -- live public-intake path (submitApplication.ts / the
    -- submit_public_application() RPC) already receives and validates a
    -- real Offer at submission time, so wiring it to also stamp this
    -- column is a natural, low-risk follow-up, not done in this pass.
    --
    -- intended_cohort_id: nullable, PERMANENTLY optional (an individual
    -- Offer like The Living Example has no cohorts at all; a group
    -- Offer's applicant may not have stated one). This is a snapshot of
    -- intent AT APPLICATION TIME — never automatically kept in sync with
    -- deals.cohort_id or enrollments.cohort_id, which are separate,
    -- later-in-time facts that may legitimately differ.
    offer_id bigint,
    intended_cohort_id bigint,
    -- Review outcomes are distinct on purpose (Native Applications slice,
    -- §1): 'approved' means "qualified for a sales call", not "Leif wants
    -- to work with them" — that call still happens later. The generic
    -- 'rejected' value is retired in favor of the specific reason.
    --
    -- 'denied' and 'waitlist' (Phase 4H) are HISTORICAL-IMPORT-ONLY —
    -- preserved truthfully from source Notion Status values that have no
    -- honest current equivalent ('Denied' proves a decline without a
    -- specific modern reason; 'Waitlist' proves an open, undecided
    -- disposition). Neither is ever set by a live review action — see
    -- reviewApplication.ts's separately-typed ApplicationReviewOutcome,
    -- which deliberately excludes both. 'waitlist' is NOT the same
    -- concept as waitlist_entries (actual operational waitlist
    -- membership) — this only preserves what the Application record
    -- itself said at submission time.
    status text not null default 'pending',
    submitted_at timestamp with time zone not null default now(),
    reviewed_at timestamp with time zone,
    -- Application questions differ by Offer and will evolve; jsonb avoids a
    -- migration every time the question set changes. No fixed schema yet.
    raw_answers jsonb not null default '{}'::jsonb,
    -- Free text for now; shaped to hold a future AI-generated summary.
    summary text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint applications_status_check check (status in ('pending', 'approved', 'needs_higher_care', 'not_fit', 'do_not_engage', 'denied', 'waitlist')),
    constraint applications_source_check check (source in ('public_form', 'historical_import'))
);

-- The commercial/client lifecycle after a successful sale. At most one per
-- Opportunity (enforced by the unique index below), which is also what makes
-- handle_deal_saved()'s Won -> Enrollment creation idempotent.
create table public.enrollments (
    id bigint generated by default as identity primary key,
    opportunity_id bigint not null,
    status text not null default 'onboarding',
    start_date date,
    end_date date,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    -- 'withdrawn' is terminal like 'completed', and exists because a
    -- person who signed up and then left before finishing is neither. Its
    -- absence forced the historical importer to choose between erasing that
    -- someone ever enrolled and labelling them "Completed" — see
    -- useClientsGrouped.ts, which files every terminal status under Past.
    -- 'ended': the container ran its course without successful completion
    -- and without a formal withdrawal. Neutral about the person on purpose.
    constraint enrollments_status_check check (status in ('onboarding', 'active', 'offboarding', 'completed', 'withdrawn', 'ended'))
);

-- The AGREED payment schedule for a Deal, for arrangements the equal-
-- installment snapshot on deals cannot express: a deposit plus a later
-- balance, unequal amounts, specific due dates, some already paid.
-- Deliberately NOT a ledger of financial transactions — it records what was
-- agreed and what is believed honoured, which is a different claim from
-- "Stripe confirms this payment". source/paid_on/stripe_payment_intent_id
-- keep those apart, enforced by the provenance check below: only a
-- stripe-sourced item may carry a payment intent, and only a stripe-sourced
-- item may claim Stripe as evidence.
create table public.deal_payment_schedule_items (
    id bigint generated by default as identity primary key,
    deal_id bigint not null,
    amount numeric(10, 2) not null,
    -- Ordinal within the schedule, so "deposit then balance" keeps its order
    -- even when neither item has a due date.
    sequence smallint not null default 1,
    -- Null when genuinely unknown.
    due_date date,
    status text not null default 'scheduled',
    -- Null when a payment is known to have happened but the date is not.
    -- Never a placeholder to satisfy NOT NULL.
    paid_on date,
    -- 'owner_stated' is Leif telling us; 'stripe' means a verified external
    -- transaction and only the Stripe integration may write it.
    source text not null default 'owner_stated',
    stripe_payment_intent_id text,
    notes text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint deal_payment_schedule_items_amount_check check (amount > 0),
    constraint deal_payment_schedule_items_status_check check (status in ('scheduled', 'paid', 'void')),
    constraint deal_payment_schedule_items_source_check check (source in ('owner_stated', 'stripe', 'historical_import')),
    constraint deal_payment_schedule_items_stripe_provenance_check check (
        (source = 'stripe' and stripe_payment_intent_id is not null)
        or (source <> 'stripe' and stripe_payment_intent_id is null)
    ),
    constraint deal_payment_schedule_items_paid_on_check check (status = 'paid' or paid_on is null),
    unique (deal_id, sequence)
);

-- Scholarship Pricing + Capacity slice: the single authoritative
-- representation of scholarship-slot ownership for an Offer. One row per
-- Offer (created lazily on first grant) — `offer_id primary key` makes "at
-- most one scholarship slot holder per Offer" a structural fact, not
-- merely an enforced-at-write-time rule. `holder_deal_id` set means an
-- outstanding scholarship offer (Deal granted, not yet Won); set
-- `holder_enrollment_id` instead means a current scholarship Enrollment
-- (onboarding/active/offboarding); both null means free; both set is
-- impossible (see the check constraint below). Deliberately a table
-- separate from `offers` itself — co-locating this fast-changing
-- operational field on the same row as slow-changing Offer configuration
-- would make every grant/release contend for the same row lock as an
-- unrelated price edit. Never written directly by the app — only by
-- handle_deal_saved() (grant/release) and handle_deal_won() (Deal ->
-- Enrollment transition) and handle_enrollment_scholarship_slot_transition()
-- (Enrollment completion release / backward-correction reclaim). See
-- scholarship_slot_events below for the append-only audit trail of every
-- transition this table itself never keeps.
create table public.scholarship_slots (
    id bigint generated by default as identity primary key,
    -- The structural "at most one slot per Offer" guarantee — a plain
    -- unique constraint (not the primary key itself, so this resource
    -- still has an ordinary `id`, like every other react-admin resource in
    -- this app) is exactly as strict as a primary key would be here.
