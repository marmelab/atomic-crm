-- Extensions
create extension if not exists "http" with schema "extensions";
create extension if not exists "citext" with schema "extensions";

-- Private schema (used by sales policies migration)
create schema if not exists "private";

--
-- Businesses
-- Every row of business data belongs to a business (business_id). A user can
-- be a member of several businesses and works in one at a time: the current
-- business (sales.current_business_id). The business_id columns of the data
-- tables are declared in 09_businesses.sql; helpers in 02_functions.sql;
-- policies in 05_policies.sql.
--

create type public.business_role as enum ('owner', 'manager', 'specialist', 'storekeeper', 'accountant', 'partner');

create table public.businesses (
    id uuid not null default gen_random_uuid() primary key,
    name text not null,
    country_code text,
    is_demo boolean not null default false,
    created_at timestamp with time zone not null default now(),
    created_by uuid,
    constraint businesses_name_length check (length(btrim(name)) between 1 and 200),
    -- Sanctions: businesses from Russia and Belarus are not served (TZ section 2)
    constraint businesses_country_code_format check (country_code ~ '^[A-Z]{2}$' and country_code not in ('RU', 'BY'))
);

create table public.members (
    business_id uuid not null,
    user_id uuid not null,
    role public.business_role not null,
    disabled boolean not null default false,
    created_at timestamp with time zone not null default now(),
    primary key (business_id, user_id)
);

create table public.companies (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    sector text,
    size smallint,
    linkedin_url text,
    website extensions.citext,
    phone_number text,
    address text,
    zipcode text,
    city text,
    state_abbr text,
    sales_id bigint,
    context_links json,
    country text,
    description text,
    revenue text,
    tax_identifier text,
    logo jsonb
);

create table public.contacts (
    id bigint generated by default as identity primary key,
    first_name text,
    last_name text,
    gender text,
    title text,
    background text,
    avatar jsonb,
    first_seen timestamp with time zone,
    last_seen timestamp with time zone,
    has_newsletter boolean,
    status text,
    tags bigint[],
    company_id bigint,
    sales_id bigint,
    linkedin_url text,
    email_jsonb jsonb,
    phone_jsonb jsonb
);

create table public.contact_notes (
    id bigint generated by default as identity (sequence name public."contactNotes_id_seq") not null,
    contact_id bigint not null,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    status text,
    attachments jsonb[]
);

create table public.deals (
    id bigint generated by default as identity primary key,
    name text not null,
    company_id bigint,
    contact_ids bigint[],
    categories text[],
    stage text not null,
    description text,
    amount bigint,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    archived_at timestamp with time zone,
    expected_closing_date date,
    sales_id bigint,
    index smallint,
    -- Rejects implausible dates, e.g. typos such as 5-digit years, plus BC dates and infinity, which the UI cannot display
    constraint deals_expected_closing_date_range check (expected_closing_date between '1900-01-01' and '2900-12-31')
);

create table public.deal_notes (
    id bigint generated by default as identity (sequence name public."dealNotes_id_seq") not null,
    deal_id bigint not null,
    type text,
    text text,
    date timestamp with time zone default now(),
    sales_id bigint,
    attachments jsonb[]
);

create table public.sales (
    id bigint generated by default as identity primary key,
    first_name text not null default 'Pending'::text,
    last_name text not null default 'Pending'::text,
    email extensions.citext not null,
    user_id uuid not null,
    avatar jsonb,
    secondary_emails jsonb not null default '[]'::jsonb,
    current_business_id uuid,
    constraint sales_secondary_emails_is_array check (jsonb_typeof(secondary_emails) = 'array')
);

create unique index uq__sales__user_id on public.sales using btree (user_id);

create table public.tags (
    id bigint generated by default as identity primary key,
    name text not null,
    color text not null
);

create table public.tasks (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    type text,
    text text,
    due_date timestamp with time zone,
    done_date timestamp with time zone,
    sales_id bigint,
    created_at timestamp with time zone not null default now()
);

-- One configuration row per business: id is the business id.
create table public.configuration (
    id uuid not null primary key,
    config jsonb not null default '{}'::jsonb
);

create table public.favicons_excluded_domains (
    id bigint generated by default as identity primary key,
    domain text not null
);

create table public.user_invitations (
    user_id uuid primary key,
    business_id uuid,
    role public.business_role
);

--
-- Foreign keys
-- (references between business data tables: 09_businesses.sql)
--

alter table public.businesses
    add constraint businesses_created_by_fkey foreign key (created_by) references auth.users(id) on delete set null;

alter table public.members
    add constraint members_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;

alter table public.members
    add constraint members_user_id_fkey foreign key (user_id) references auth.users(id) on delete cascade;

alter table public.sales
    add constraint sales_current_business_id_fkey foreign key (current_business_id) references public.businesses(id) on delete set null;

alter table public.user_invitations
    add constraint user_invitations_business_id_fkey foreign key (business_id) references public.businesses(id) on delete cascade;

alter table public.configuration
    add constraint configuration_id_fkey foreign key (id) references public.businesses(id) on delete cascade;


alter table public.companies
    add constraint companies_sales_id_fkey foreign key (sales_id) references public.sales(id);

alter table public.contacts
    add constraint contacts_sales_id_fkey foreign key (sales_id) references public.sales(id);

alter table public.contact_notes
    add constraint "contactNotes_sales_id_fkey" foreign key (sales_id) references public.sales(id) on update cascade on delete cascade;

alter table public.deals
    add constraint deals_sales_id_fkey foreign key (sales_id) references public.sales(id);

alter table public.deal_notes
    add constraint "dealNotes_sales_id_fkey" foreign key (sales_id) references public.sales(id);

alter table public.sales
    add constraint sales_user_id_fkey foreign key (user_id) references auth.users(id);

-- Legacy primary key constraint names (from before snake_case rename)
alter table only public.contact_notes
    add constraint "contactNotes_pkey" primary key (id);

alter table only public.deal_notes
    add constraint "dealNotes_pkey" primary key (id);

--
-- Indexes on foreign keys
--

create index contact_notes_contact_id_idx on public.contact_notes using btree (contact_id);
create index contacts_company_id_idx on public.contacts using btree (company_id);
create index deal_notes_deal_id_idx on public.deal_notes using btree (deal_id);
create index deals_company_id_idx on public.deals using btree (company_id);
create index members_user_id_idx on public.members using btree (user_id);
