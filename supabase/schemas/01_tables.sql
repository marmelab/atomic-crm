-- Enrollment's own sequential 12-slot cadence — assigned by
-- sync_year_planning_calendar's own assignment pass (append-only, never
-- reassigned/renumbered — see that module's own header comment for the
-- full reasoning). A Living Example Enrollment's real business model is
-- 12 total session opportunities grouped into 4 Service Periods of
-- exactly 3 each; WHEN each one falls is whatever the Year Planning
-- calendar's own chronological sequence of qualifying windows says, not
-- a 30/31-day calendar month — a Service Period can span more or less
-- than a literal month, and a calendar gap (holiday, travel) never
-- consumes one of the 12 slots or creates a phantom one.
--
-- Deliberately SNAPSHOTS window_start/window_end/raw_title at the moment
-- of assignment (same "historical integrity from a snapshot, never a
-- live join back" convention as deals.offer_name_snapshot/
-- offer_price_snapshot on offers) — this is what makes an already-
-- assigned slot's own ordinal, Service Period number, and displayed
-- dates immune to a LATER edit to the source calendar event. source_window_id
-- is kept for traceability only, never re-read for display or
-- fulfillment-matching once assigned.
create table public.enrollment_expected_sessions (
    id bigint generated by default as identity primary key,
    enrollment_id bigint not null,
    source_window_id bigint not null,
    -- 1-12, one Enrollment's own full cadence. Service Period number is
    -- always ceil(ordinal / 3) — deliberately not a stored column (pure
    -- derived arithmetic, never allowed to drift out of sync with
    -- ordinal).
    ordinal smallint not null,
    window_start date not null,
    window_end date not null,
    raw_title text not null,
    created_at timestamp with time zone not null default now(),
    constraint enrollment_expected_sessions_ordinal_check check (ordinal between 1 and 12)
);

-- One slot per position per Enrollment (the assignment pass's own
-- append-only idempotency boundary), and a given shared calendar window
-- is assigned to a specific Enrollment's cadence at most once.
create unique index enrollment_expected_sessions_enrollment_ordinal_idx on public.enrollment_expected_sessions (enrollment_id, ordinal);
create unique index enrollment_expected_sessions_enrollment_window_idx on public.enrollment_expected_sessions (enrollment_id, source_window_id);

-- Client + Session Operations cadence correction: the resolvable
-- exception row — mirrors sales_calls' own "the record IS the alert"
-- shape (resolveUnmatchedSalesCall.ts), never a second alert system. One
-- row per (active Enrollment, assigned session slot) pair — created
-- either by sync_year_planning_calendar's own detection pass (a closed
-- slot with no fulfilling session) or synchronously the moment a
-- fulfilling session is marked No-show (see markClientSessionNoShow.ts).
-- Never guessed at or auto-classified (Atomic handles certainty; Leif
-- handles ambiguity). classification/resolved_at both null means still
-- unresolved and surfaced on the Dashboard's existing Needs Attention
-- section via its own linked Task (see tasks.cadence_issue_id below) —
-- same "durable row + Task" pairing resolve_sales_call already
-- established, not a new pattern.
--
-- Service Period model correction: points at the Enrollment's own frozen
-- enrollment_expected_sessions slot (never the shared, editable
-- expected_session_windows row directly) — so a later edit to the source
-- calendar event can never shift which slot this issue is about.
--
-- Human-acceptance correction (state machine fix): a classification is a
-- human JUDGMENT, not an immutable fact — Leif can change it (known_skip
-- -> rescheduled -> missed_ghosted) or reopen/clear it entirely if made
-- by mistake, always leaving THIS row holding the CURRENT state while
-- client_session_cadence_issue_events below holds the full history.
-- resolved_at set with classification null means "resolved because
-- fulfillment was restored" (an auto-resolve, e.g. Undo No-show put a
-- session back) — distinct from a real human classification, and the
-- ONLY state this table's own automated callers (markClientSessionNoShow.ts/
-- reverseClientSessionNoShow.ts, sync_year_planning_calendar's detection
-- pass) are ever allowed to create or reopen on their own; a row already
-- carrying a real classification is never silently touched by them.
create table public.client_session_cadence_issues (
    id bigint generated by default as identity primary key,
    enrollment_id bigint not null,
    enrollment_expected_session_id bigint not null,
    -- Leif's own explicit classification — never inferred. See
    -- resolveClientSessionCadenceIssue.ts for what each one means
    -- operationally (known_skip/rescheduled never count as a client
    -- failure; missed_ghosted is the one genuine missed obligation).
    -- Null while unresolved, OR while resolved-via-restored-fulfillment
    -- (see this table's own header comment) — never conflated with a
    -- real human decision.
    classification text,
    note text,
    resolved_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint client_session_cadence_issues_classification_check check (classification in ('known_skip', 'rescheduled', 'missed_ghosted'))
);

-- At most one issue row per (Enrollment, slot) — the detection pass's
-- own find-or-create idempotency boundary, same role as
-- client_sessions_acuity_appointment_id_idx above.
create unique index client_session_cadence_issues_enrollment_slot_idx on public.client_session_cadence_issues (enrollment_id, enrollment_expected_session_id);

-- Append-only history for the resolvable row above — same rationale as
-- every other current-state-row + event-log pair in this schema
-- (sales_calls/sales_call_events, client_sessions/client_session_events):
-- a classification changed (or reopened) more than once must never
-- collapse into a single summary field. 'created' is logged once, at
-- issue creation; 'resolved' the first time a classification (or an
-- auto-resolve) is set; 'reclassified' when an already-resolved issue's
-- classification changes to a different one; 'reopened' when a
-- classification is cleared/reopened (by Leif) or a resolved-via-
-- fulfillment issue is reactivated because fulfillment was lost again
-- (e.g. a later No-show).
create table public.client_session_cadence_issue_events (
    id bigint generated by default as identity primary key,
    cadence_issue_id bigint not null,
    kind text not null,
    -- The classification AS OF this event, if any (kind = 'resolved' or
    -- 'reclassified') — null for 'created'/'reopened'.
    classification text,
    note text,
    occurred_at timestamp with time zone not null default now(),
    created_at timestamp with time zone not null default now(),
    constraint client_session_cadence_issue_events_kind_check check (kind in ('created', 'resolved', 'reclassified', 'reopened')),
    constraint client_session_cadence_issue_events_classification_check check (classification in ('known_skip', 'rescheduled', 'missed_ghosted'))
);

create index client_session_cadence_issue_events_issue_id_idx on public.client_session_cadence_issue_events using btree (cadence_issue_id);

