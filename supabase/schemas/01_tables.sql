-- Append-only history of every genuine stage transition an Opportunity has
-- made (Kanban queue-ordering slice) — the same "durable event history
-- alongside an easy current-state field" split already used for Sales
-- Calls (sales_calls/sales_call_events). One row per stage the Opportunity
-- has ever entered, written exactly once per genuine change by
-- record_deal_stage_event() below. Deliberately narrow: this exists only
-- to preserve stage transitions, not a general audit log of every field
-- change. Preserves what deals.stage_entered_at alone cannot: durations
-- through EARLIER stages (Application -> Call Booked -> Decision ->
-- Committed -> Won), needed for future per-offer funnel timing.
create table public.deal_stage_events (
