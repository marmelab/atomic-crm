-- Contracts + Onboarding slice: one row per (Enrollment x applicable
-- requirement), created once by handle_deal_won() below at the moment the
-- Enrollment itself is created (same idempotency gate, so a duplicate
-- Stripe webhook can never re-seed these any more than it can re-create
-- the Enrollment). label/is_required are SNAPSHOTTED from
-- onboarding_requirement_templates at that moment — deliberately not a
-- live join back to it, so a later template edit never rewrites an
-- already-created Enrollment's own checklist history (same rationale as
