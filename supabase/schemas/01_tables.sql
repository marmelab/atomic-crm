-- The durable current-state record for a sales call/appointment (Acuity/
-- Sales Call Lifecycle slice), one row per LOGICAL appointment — a
-- reschedule updates this row rather than creating a second one, so it
-- can never look like two independent calls in later conversion
-- analytics. Individual lifecycle facts (booked/rescheduled/cancelled/
-- attendance recorded, with occurred_at and old/new values) are preserved
-- separately in sales_call_events; this row is only ever current/summary
-- state.
create table public.sales_calls (
    id bigint generated by default as identity primary key,
    -- Nullable: a booking that can't be safely matched to exactly one
    -- active Opportunity is preserved with opportunity_id = null rather
    -- than guessed — see sales-calls/matchAcuityBooking.ts. Surfaced via
    -- a "Resolve Sales Call" task rather than silently buried.
    opportunity_id bigint,
    -- Always resolved (normalized-email match-or-create, Native
    -- Application Intake's own matching principle) even when the
    -- Opportunity is ambiguous.
    contact_id bigint not null,
    status text not null default 'booked',
    -- Set once at creation, never updated by a reschedule.
    original_scheduled_at timestamp with time zone not null,
    -- The current/latest scheduled time. Mirrored onto the owning
    -- Opportunity's sales_call_at (a denormalized convenience field, kept
    -- exactly as it already was) by sync_deal_sales_call_at() below.
    scheduled_at timestamp with time zone not null,
    reschedule_count smallint not null default 0,
    last_rescheduled_at timestamp with time zone,
    cancelled_at timestamp with time zone,
    -- Always a human/CRM action (Complete Sales Call), never inferred
    -- from Acuity — an appointment's time passing does not prove
    -- attendance.
    attendance text,
    attendance_recorded_at timestamp with time zone,
    source text not null default 'manual',
    acuity_appointment_id text,
    acuity_appointment_type_id text,
    -- Unmatched Sales Call Resolution slice: distinct from
    -- opportunity_id — a booking can be unresolved (both null), matched
    -- (opportunity_id set), or deliberately dismissed (dismissed_at set,
    -- opportunity_id stays null forever). Never overload
    -- opportunity_id = null to mean both "not yet resolved" and
    -- "resolved as not-a-sales-situation" — a duplicate Acuity webhook
    -- replay needs to tell those apart to never resurrect a dismissed
    -- booking's alert.
    dismissed_at timestamp with time zone,
    dismissal_reason text,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    -- 'completed' added (Go-Live Blocker: Sales-Call No-Show/Rebooking
    -- slice): a concluded call (attendance recorded, attended or no_show)
    -- must leave 'booked' — sales_calls_one_booked_per_opportunity_idx
    -- below is a PARTIAL unique index on (opportunity_id) WHERE status =
    -- 'booked', so a concluded call that never transitions away from
    -- 'booked' silently blocks a genuine rebooking's fresh INSERT with a
    -- unique-violation. See completeSalesCallOutcome.ts's own comment.
    constraint sales_calls_status_check check (status in ('booked', 'completed', 'cancelled')),
    constraint sales_calls_attendance_check check (attendance in ('attended', 'no_show')),
    constraint sales_calls_source_check check (source in ('acuity', 'manual')),
    constraint sales_calls_schedule_precision_check check (schedule_precision in ('exact', 'date_only')),
    -- No row may claim a time it does not have, and no real appointment may
    -- lose the time it does.
    constraint sales_calls_schedule_shape_check check (
        (schedule_precision = 'exact' and original_scheduled_at is not null and scheduled_at is not null)
        or (schedule_precision = 'date_only' and original_scheduled_at is null and scheduled_at is null)
    ),
    -- A date-only call is history: there is no time to show up at, so it can
    -- never be a live booking.
    constraint sales_calls_date_only_not_booked_check check (schedule_precision = 'exact' or status <> 'booked')
);

-- Defense-in-depth alongside the domain-layer duplicate-booking check
-- (sales-calls/bookSalesCall.ts): at most one currently-booked call per
-- Opportunity — a second incoming booking for the same Opportunity is a
-- reschedule of the existing row, never a second one.
create unique index sales_calls_one_booked_per_opportunity_idx on public.sales_calls (opportunity_id) where (status = 'booked' and opportunity_id is not null);
create unique index sales_calls_acuity_appointment_id_idx on public.sales_calls (acuity_appointment_id) where (acuity_appointment_id is not null);

-- Append-only lifecycle history for a sales_calls row (Leif's own decision:
