--
-- Country packs
-- Everything that differs between countries is data with validity dates, never
-- code (TZ section 7): language and formats, default currency and time zone,
-- requisite fields and how to check them, tax rates, document numbering.
-- Reference data, read by every signed-in user, changed only by migrations.
-- The rows themselves live in the migrations (e.g. 20261113130000_country_packs.sql).
--

create extension if not exists "btree_gist" with schema "extensions";

create table public.country_packs (
    code text not null primary key,
    name text not null,
    -- BCP 47 language of the country; the interface falls back to English
    -- when it has no translation for it
    language text not null,
    -- Formats of dates, numbers and money, e.g. uk-UA
    locale text not null,
    -- Default base currency of a business (ISO 4217)
    currency text not null,
    -- Default time zone of a business (IANA)
    timezone text not null,
    is_active boolean not null default true,
    created_at timestamp with time zone not null default now(),
    constraint country_packs_code_format check (code ~ '^[A-Z]{2}$' and code not in ('RU', 'BY')),
    constraint country_packs_currency_format check (currency ~ '^[A-Z]{3}$')
);

-- Requisite fields of a company in a country. A field is required, or belongs
-- to a required_group in which at least one field must be filled (e.g. a
-- Ukrainian company has an EDRPOU code, a sole proprietor an individual tax number).
create table public.requisite_fields (
    id bigint generated by default as identity primary key,
    country_code text not null,
    key text not null,
    -- How the value is checked: see public.requisite_is_valid()
    validator text not null,
    -- English label; the interface translates requisites.<key>
    label text not null,
    required boolean not null default false,
    required_group text,
    sort_order smallint not null default 0,
    valid_from date not null,
    valid_to date,
    constraint requisite_fields_key_format check (key ~ '^[a-z][a-z0-9_]*$'),
    constraint requisite_fields_validator check (validator in ('edrpou', 'ipn', 'nip', 'regon', 'iban')),
    constraint requisite_fields_validity check (valid_to is null or valid_to > valid_from),
    constraint requisite_fields_no_overlap exclude using gist (
        country_code with =, key with =, daterange(valid_from, valid_to) with &&
    )
);

-- Tax rates in percent, with the period they apply to. valid_from is the date
-- from which the product applies the rate, not necessarily when the law
-- introduced it.
create table public.tax_rates (
    id bigint generated by default as identity primary key,
    country_code text not null,
    tax text not null default 'vat',
    code text not null,
    rate numeric(6,3) not null,
    label text not null,
    valid_from date not null,
    valid_to date,
    constraint tax_rates_rate_range check (rate >= 0 and rate < 100),
    constraint tax_rates_validity check (valid_to is null or valid_to > valid_from),
    constraint tax_rates_no_overlap exclude using gist (
        country_code with =, tax with =, code with =, daterange(valid_from, valid_to) with &&
    )
);

-- Document numbering. Pattern tokens: {YYYY} year, {YY}, {MM} month,
-- {N...} the sequence, zero-padded to the number of N.
create table public.numbering_rules (
    id bigint generated by default as identity primary key,
    country_code text not null,
    document_type text not null,
    pattern text not null,
    reset_period text not null,
    valid_from date not null,
    valid_to date,
    constraint numbering_rules_pattern check (pattern ~ '\{N+\}'),
    constraint numbering_rules_reset_period check (reset_period in ('never', 'yearly', 'monthly')),
    constraint numbering_rules_validity check (valid_to is null or valid_to > valid_from),
    constraint numbering_rules_no_overlap exclude using gist (
        country_code with =, document_type with =, daterange(valid_from, valid_to) with &&
    )
);

alter table public.requisite_fields
    add constraint requisite_fields_country_code_fkey foreign key (country_code) references public.country_packs(code) on delete cascade;
alter table public.tax_rates
