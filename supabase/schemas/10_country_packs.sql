--
-- Requisite checks (same rules as src/components/atomic-crm/requisites/validators.ts)
--

CREATE OR REPLACE FUNCTION "public"."normalize_requisite"("p_validator" "text", "p_value" "text") RETURNS "text"
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
    select case
        when p_validator = 'iban' then upper(regexp_replace(p_value, '\s', '', 'g'))
        else regexp_replace(p_value, '[\s-]', '', 'g')
    end
$$;

CREATE OR REPLACE FUNCTION "public"."requisite_is_valid"("p_validator" "text", "p_value" "text") RETURNS boolean
    LANGUAGE "plpgsql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
declare
  v text := public.normalize_requisite(p_validator, p_value);
  d int[];
  weights int[];
  total int := 0;
  control int;
  country text;
  expected_length int;
  digits_string text := '';
  ch text;
begin
  if v is null then
    return false;
  end if;

  if p_validator = 'iban' then
    if v !~ '^[A-Z]{2}[0-9]{2}[A-Z0-9]+$' or length(v) < 15 or length(v) > 34 then
      return false;
    end if;
    country := left(v, 2);
    -- Sanctions: bank accounts in Russia and Belarus are not accepted
    if country in ('RU', 'BY') then
      return false;
    end if;
    expected_length := case country when 'UA' then 29 when 'PL' then 28 end;
    if expected_length is not null and length(v) <> expected_length then
      return false;
    end if;
    foreach ch in array regexp_split_to_array(substr(v, 5) || left(v, 4), '') loop
      digits_string := digits_string || case when ch ~ '[0-9]' then ch else (ascii(ch) - 55)::text end;
    end loop;
    return digits_string::numeric % 97 = 1;
  end if;

  if v !~ '^[0-9]+$' then
    return false;
  end if;
  d := array(select c::int from regexp_split_to_table(v, '') as c);

  if p_validator = 'edrpou' then
    if length(v) <> 8 then return false; end if;
    weights := case when v::bigint < 30000000 or v::bigint > 60000000
      then array[1, 2, 3, 4, 5, 6, 7] else array[7, 1, 2, 3, 4, 5, 6] end;
    select sum(d[i] * weights[i]) into total from generate_series(1, 7) as i;
    control := total % 11;
    if control = 10 then
      select sum(d[i] * (weights[i] + 2)) into total from generate_series(1, 7) as i;
      control := total % 11;
      if control = 10 then control := 0; end if;
    end if;
    return control = d[8];
  end if;

  if p_validator = 'ipn' then
    if length(v) <> 10 then return false; end if;
    weights := array[-1, 5, 7, 9, 4, 6, 10, 5, 7];
    select sum(d[i] * weights[i]) into total from generate_series(1, 9) as i;
    return (((total % 11) + 11) % 11) % 10 = d[10];
  end if;

  if p_validator = 'nip' then
    if length(v) <> 10 then return false; end if;
    weights := array[6, 5, 7, 2, 3, 4, 5, 6, 7];
    select sum(d[i] * weights[i]) into total from generate_series(1, 9) as i;
    control := total % 11;
    return control <> 10 and control = d[10];
  end if;

  if p_validator = 'regon' then
    if length(v) not in (9, 14) then return false; end if;
    weights := array[8, 9, 2, 3, 4, 5, 6, 7];
    select sum(d[i] * weights[i]) into total from generate_series(1, 8) as i;
    control := total % 11 % 10;
    if control <> d[9] then return false; end if;
    if length(v) = 9 then return true; end if;
    weights := array[2, 4, 8, 5, 0, 9, 7, 3, 6, 1, 2, 4, 8];
    select sum(d[i] * weights[i]) into total from generate_series(1, 13) as i;
    return total % 11 % 10 = d[14];
  end if;

  return false;
end;
$$;

-- Requisite fields of a country that apply on a date
CREATE OR REPLACE FUNCTION "public"."active_requisite_fields"("p_country_code" "text", "p_on" "date" DEFAULT CURRENT_DATE) RETURNS SETOF "public"."requisite_fields"
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
    select * from public.requisite_fields f
    where f.country_code = p_country_code
      and f.valid_from <= p_on
      and (f.valid_to is null or f.valid_to > p_on)
    order by f.sort_order, f.key
$$;

-- Requisite fields that still need a value: required ones, and groups with no
-- field filled (one entry per group, named after the group).
CREATE OR REPLACE FUNCTION "public"."missing_requisites"("p_country_code" "text", "p_requisites" "jsonb") RETURNS "text"[]
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
    select coalesce(array_agg(missing order by missing), '{}')
    from (
        select f.key as missing
        from public.active_requisite_fields(p_country_code) f
        where f.required and coalesce(p_requisites ->> f.key, '') = ''
        union
        select f.required_group
        from public.active_requisite_fields(p_country_code) f
        where f.required_group is not null
        group by f.required_group
        having bool_and(coalesce(p_requisites ->> f.key, '') = '')
    ) m
$$;

-- Normalizes the requisites of a business and rejects unknown fields and
-- invalid values (SQLSTATE 23514, the offending keys in the detail).
CREATE OR REPLACE FUNCTION "public"."check_business_requisites"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
begin
  if new.requisites = '{}'::jsonb then
    return new;
  end if;

  if new.country_code is null then
    raise exception 'Choose the country of the business before its requisites'
      using errcode = '23514';
  end if;

  -- public.validated_requisites() lives in 13_counterparties.sql
  new.requisites := public.validated_requisites(new.country_code, new.requisites);
  return new;
end;
$$;

create or replace trigger check_business_requisites
    before insert or update of requisites, country_code on public.businesses
    for each row execute function public.check_business_requisites();

