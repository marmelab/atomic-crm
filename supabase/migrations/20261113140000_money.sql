-- Money and time (stage 1.3): structure as in supabase/schemas/11_money.sql,
-- plus moving existing amounts to minor units.
--
-- Amounts are integers in the smallest unit of their currency (kopecks,
-- grosze, cents) next to an ISO 4217 currency code. A business has a base
-- currency and a time zone, by default those of its country pack.
--

-- Digits after the decimal point of a currency (ISO 4217 minor unit)
CREATE OR REPLACE FUNCTION "public"."currency_minor_digits"("p_currency" "text") RETURNS integer
    LANGUAGE "sql" IMMUTABLE
    SET "search_path" TO ''
    AS $$
    select case
        when p_currency in ('BIF', 'CLP', 'DJF', 'GNF', 'ISK', 'JPY', 'KMF', 'KRW', 'PYG', 'RWF', 'UGX', 'UYI', 'VND', 'VUV', 'XAF', 'XOF', 'XPF') then 0
        when p_currency in ('BHD', 'IQD', 'JOD', 'KWD', 'LYD', 'OMR', 'TND') then 3
        else 2
    end
$$;

alter table public.businesses add column currency text;
alter table public.businesses add column timezone text;

-- Existing businesses: their pack, else the currency chosen in the settings, else Ukraine
update public.businesses b
set currency = coalesce(p.currency, c.config ->> 'currency', 'UAH'),
    timezone = coalesce(p.timezone, 'Europe/Kyiv')
from public.businesses b2
left join public.country_packs p on p.code = b2.country_code
left join public.configuration c on c.id = b2.id
where b2.id = b.id;

alter table public.businesses alter column currency set not null;
alter table public.businesses alter column timezone set not null;
alter table public.businesses
    add constraint businesses_currency_format check (currency ~ '^[A-Z]{3}$');

-- Fills the base currency and time zone of a business from its country pack
-- when they are not given (Ukrainian defaults for a business without a country).
CREATE OR REPLACE FUNCTION "public"."set_business_defaults"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  pack public.country_packs;
begin
  select * into pack from public.country_packs where code = new.country_code;
  new.currency := coalesce(new.currency, pack.currency, 'UAH');
  new.timezone := coalesce(new.timezone, pack.timezone, 'Europe/Kyiv');
  return new;
end;
$$;

create or replace trigger set_business_defaults
    before insert on public.businesses
    for each row execute function public.set_business_defaults();

-- Deal amounts are in minor units of deals.currency (the business currency by default)
alter table public.deals add column currency text;

-- Existing deals: business currency, whole units become minor units
update public.deals d
set currency = b.currency,
    amount = d.amount * power(10, public.currency_minor_digits(b.currency))::bigint
from public.businesses b
where b.id = d.business_id;

alter table public.deals alter column currency set not null;
alter table public.deals
    add constraint deals_currency_format check (currency ~ '^[A-Z]{3}$');
comment on column public.deals.amount is 'Integer amount in minor units of currency (kopecks, grosze, cents)';

CREATE OR REPLACE FUNCTION "public"."set_deal_currency"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if new.currency is null then
    select b.currency into new.currency from public.businesses b where b.id = new.business_id;
  end if;
  return new;
end;
$$;

create or replace trigger set_deal_currency
    before insert on public.deals
    for each row execute function public.set_deal_currency();

-- Exchange rates (filled from national bank feeds in stage 7). One unit of
-- base_currency is worth rate units of quote_currency on rate_date.
create table public.fx_rates (
    id bigint generated by default as identity primary key,
    base_currency text not null,
    quote_currency text not null,
    rate numeric(20,10) not null,
    rate_date date not null,
    source text not null,
    created_at timestamp with time zone not null default now(),
    constraint fx_rates_currency_format check (base_currency ~ '^[A-Z]{3}$' and quote_currency ~ '^[A-Z]{3}$' and base_currency <> quote_currency),
    constraint fx_rates_rate_positive check (rate > 0),
    constraint fx_rates_unique unique (base_currency, quote_currency, rate_date, source)
);

alter table public.fx_rates enable row level security;
create policy "Read reference data" on public.fx_rates for select to authenticated using (true);

grant select on table public.fx_rates to authenticated;
grant all on table public.fx_rates to service_role;

revoke all on function public.currency_minor_digits(text) from public, anon;
grant all on function public.currency_minor_digits(text) to authenticated;
grant all on function public.currency_minor_digits(text) to service_role;

grant all on function public.set_business_defaults() to authenticated;
grant all on function public.set_business_defaults() to service_role;

grant all on function public.set_deal_currency() to authenticated;
grant all on function public.set_deal_currency() to service_role;
