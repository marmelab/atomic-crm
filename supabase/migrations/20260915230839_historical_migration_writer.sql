-- Historical Migration slice: the controlled-import mechanism for the
-- one-time historical Notion/Acuity/Stripe data migration (the frozen
-- Phase 3 dry-run manifest). This migration adds the MECHANISM only — it
-- imports zero historical client records itself.
--
-- Three problems solved, each with the smallest change that solves it:
--
-- 1. Historical Won deals must not fire live onboarding. handle_deal_won()
--    unconditionally creates a real Enrollment (status='onboarding') plus
--    onboarding checklist Tasks due "now() + 3 days" the instant
--    stage='won' is set (INSERT or UPDATE) -- correct for a real sale
--    closing today, wrong for a historical record from 2024/2025. Guarded
--    to return early when migration mode is on; the importer inserts the
--    correct, truthful FINAL-state Enrollment itself.
--
-- 2. Historical timestamps must survive, not get overwritten with now().
--    set_deal_stage_entered_at() and record_enrollment_status_event() both
--    unconditionally stamp now() -- guarded the same way. deals has a
--    stage_entered_at column to preserve a caller-supplied historical value
--    from; enrollments has no equivalent column, so for that one the
--    importer inserts enrollment_status_events rows itself, directly, with
--    the real historical date(s).
--
-- 3. Only a narrowly-authorized caller may ever turn migration mode on.
--    set_historical_migration_mode(boolean) is SECURITY DEFINER, pinned
--    search_path, and its own auth.role() check mirrors handle_deal_saved()'s
--    existing Won-authority guard exactly (NULL = trusted direct-connection
--    context, 'service_role' = the real webhook identity, anything else
--    rejected). Its ALTER-DEFAULT-PRIVILEGES grant to authenticated is
--    explicitly revoked below -- PUBLIC/anon never had it in the first
--    place (20260913230000_anon_table_grant_hardening.sql already narrowed
--    that). The GUC itself is set via set_config(..., true) -- the
--    is_local=true third argument -- so it is transaction-local by
--    PostgreSQL's own construction: it resets on COMMIT or ROLLBACK,
--    cannot leak into a later transaction on the same connection, and
--    cannot be observed by any other session at all.
--
-- Idempotency + auditability for the importer itself: historical_import_
-- records is a new, small, RLS-locked-to-service_role-only table (zero
-- policies -- see 05_policies.sql) giving a real database-enforced
-- idempotency key for entities that otherwise have none (most Pipeline/
-- Waitlist-only Contacts have neither a stripe_customer_id nor an
-- acuity_appointment_id to key off of), and a durable, queryable answer to
-- "did this record come from the 2026 historical migration" six months
-- from now. Deliberately one small table, not new columns bolted onto
-- contacts/deals/applications/waitlist_entries.
--
-- Hand-written, not CLI-generated: this sandbox has no Docker/Podman, so
-- `supabase db diff` cannot spin up its shadow database (same constraint as
-- every other hand-written migration this project has needed). Every
-- statement below matches the corresponding supabase/schemas/*.sql file
-- exactly.
--
-- This migration alone imports ZERO historical client records. It only
-- adds the mechanism a separate, explicitly-approved import step would use.

CREATE TABLE "public"."historical_import_records" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "entity_table" text NOT NULL,
    "entity_id" bigint NOT NULL,
    "source_key" text NOT NULL,
    "source_system" text NOT NULL,
    "operation" text NOT NULL,
    "batch_id" text NOT NULL,
    -- Phase 4P: see 01_tables.sql for the full rationale.
    "evidence_notes" text,
    "imported_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "historical_import_records_entity_unique" UNIQUE ("entity_table", "entity_id"),
    CONSTRAINT "historical_import_records_source_unique" UNIQUE ("entity_table", "source_key"),
    -- 'notion_application' added in Phase 4G — see 01_tables.sql's own
    -- comment: the original LE/GYU application databases are a distinct
    -- source from the downstream 'notion_pipeline'.
    CONSTRAINT "historical_import_records_source_system_check" CHECK (source_system IN ('notion_pipeline', 'notion_waitlist', 'notion_application', 'acuity', 'stripe', 'existing_crm')),
    CONSTRAINT "historical_import_records_operation_check" CHECK (operation IN ('create', 'update'))
);

CREATE INDEX "historical_import_records_batch_id_idx" ON "public"."historical_import_records" USING btree (batch_id);

ALTER TABLE "public"."historical_import_records" ENABLE ROW LEVEL SECURITY;

revoke select, insert, update, delete on table "public"."historical_import_records" from "anon";
revoke select, insert, update, delete on table "public"."historical_import_records" from "authenticated";

CREATE OR REPLACE FUNCTION "public"."set_historical_migration_mode"("enable" boolean) RETURNS "void"
    LANGUAGE "plpgsql"
    SECURITY DEFINER
    SET "search_path" TO 'public', 'pg_temp'
    AS $$
begin
  if auth.role() is not null and auth.role() <> 'service_role' then
    raise exception 'set_historical_migration_mode() is restricted to a service_role/direct-connection context';
  end if;
  perform set_config('app.migration_mode', case when enable then 'true' else 'false' end, true);
end;
$$;

revoke all on function public.set_historical_migration_mode(boolean) from public;
revoke all on function public.set_historical_migration_mode(boolean) from authenticated;
grant all on function public.set_historical_migration_mode(boolean) to service_role;

CREATE OR REPLACE FUNCTION "public"."handle_deal_won"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
declare
  v_cohort cohorts%ROWTYPE;
  v_enrollment_id bigint;
  v_contact_name text;
  v_item record;
begin
  -- Historical Migration slice: a historical Won Deal must never fire live
  -- onboarding (a real Enrollment at 'onboarding' status, checklist items,
  -- and Tasks due in 3 days from NOW) — the importer inserts the correct,
  -- truthful final-state Enrollment itself. See
  -- set_historical_migration_mode()'s own header for why this GUC check is
  -- safe: only that narrowly-restricted function can ever set it, and it is
  -- transaction-local by construction.
  if current_setting('app.migration_mode', true) = 'true' then
    return new;
  end if;

  if new.stage = 'won' and (tg_op = 'INSERT' or old.stage is distinct from 'won') then
    if new.cohort_id is not null then
      select * into v_cohort from cohorts where id = new.cohort_id;
    end if;

    -- Idempotent: the unique constraint on enrollments.opportunity_id means
    -- re-saving Won (or this trigger re-firing) never creates a duplicate.
    -- `returning ... into` only actually assigns on the genuine-insert
    -- path — the on-conflict no-op leaves v_enrollment_id null, which is
    -- exactly the signal the Contracts + Onboarding block below needs to
    -- stay just as replay-safe as the Enrollment creation it's gated on.
    insert into enrollments (opportunity_id, status, start_date, end_date)
    values (
      new.id,
      'onboarding',
      v_cohort.program_start_at::date,
      v_cohort.program_end_at::date
    )
    on conflict (opportunity_id) do nothing
    returning id into v_enrollment_id;

    if v_enrollment_id is not null then
      select trim(both ' ' from coalesce(first_name, '') || ' ' || coalesce(last_name, ''))
        into v_contact_name
        from contacts where id = new.contact_id;
      if v_contact_name is null or v_contact_name = '' then
        v_contact_name := new.name;
      end if;

      -- Seed this Enrollment's checklist from whichever requirement
      -- templates are currently active for this Deal's Offer (snapshotted,
      -- not a live reference — see onboarding_requirement_templates' own
      -- comment), one Task per REQUIRED item only (optional items get no
      -- auto-task — Contracts + Onboarding slice, §8/§11 of the
      -- architecture review).
      for v_item in
        insert into enrollment_onboarding_items
          (enrollment_id, requirement_key, label, task_text_template, is_required, sort_order)
        select v_enrollment_id, t.key, t.label, t.task_text_template, t.is_required, t.sort_order
        from onboarding_requirement_templates t
        where t.offer_id = new.offer_id and t.is_active
        returning id, is_required, task_text_template
      loop
        if v_item.is_required then
          insert into tasks (contact_id, type, text, due_date, status, enrollment_id, onboarding_item_id)
          values (
            new.contact_id,
            'onboarding_item',
            replace(v_item.task_text_template, '{name}', v_contact_name),
            -- Deliberately NOT now() — every required item due immediately
            -- at Enrollment creation would produce artificial overdue
            -- noise (someone paying late in the day reads as instantly
            -- behind). The Dashboard's Needs Onboarding section (driven
            -- directly off Enrollment state, not Tasks) is the primary
            -- "this person cannot disappear" signal; these Tasks' Overdue
            -- bucket is a secondary nudge, so a few real days of slack is
            -- correct, not a compromise.
            now() + interval '3 days',
            'pending',
            v_enrollment_id,
            v_item.id
          );
        end if;
      end loop;

      -- Scholarship Pricing + Capacity slice: atomically transition the
      -- slot this Deal holds (grant time) into Enrollment-held occupancy —
      -- a single UPDATE flipping both holder columns together, inside the
      -- same transaction as the enrollments INSERT above, so no other
      -- session can ever observe this Offer's slot as free between "Deal
      -- loses it" and "Enrollment gains it".
      if new.pricing_mode = 'scholarship' then
        update scholarship_slots
          set holder_deal_id = null, holder_enrollment_id = v_enrollment_id, updated_at = now()
          where offer_id = new.offer_id and holder_deal_id = new.id;
        if not found then
          raise exception 'Deal % reached Won as scholarship but held no scholarship slot for offer % — data inconsistency', new.id, new.offer_id;
        end if;

        insert into scholarship_slot_events (offer_id, deal_id, enrollment_id, event_type, occurred_at)
        values (new.offer_id, new.id, v_enrollment_id, 'deal_converted_to_enrollment', now());
      end if;
    end if;
  end if;
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."set_deal_stage_entered_at"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
begin
  -- Historical Migration slice: preserve the caller-supplied historical
  -- stage_entered_at verbatim instead of overwriting it with now() — see
  -- set_historical_migration_mode()'s own header.
  if current_setting('app.migration_mode', true) = 'true' then
    return new;
  end if;

  if tg_op = 'INSERT' or new.stage is distinct from old.stage then
    new.stage_entered_at := now();
  end if;
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION "public"."record_enrollment_status_event"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
begin
  -- Historical Migration slice: enrollments has no per-status timestamp
  -- column of its own to source a truthful entered_at from (unlike deals'
  -- stage_entered_at), so there is nothing safe to substitute here — the
  -- importer inserts the correct, truthful enrollment_status_events row(s)
  -- itself, directly, with the real historical date(s). See
  -- set_historical_migration_mode()'s own header.
  if current_setting('app.migration_mode', true) = 'true' then
    return new;
  end if;

  if tg_op = 'INSERT' or new.status is distinct from old.status then
    insert into enrollment_status_events (enrollment_id, status, entered_at)
    values (new.id, new.status, now());
  end if;
  return new;
end;
$$;

