-- ===========================================================================
-- Waitlist invitations: batches + per-person invitation events
-- ===========================================================================
-- Leif's real workflow: when the sales-call calendar reopens he invites a
-- large batch (30-40 people) off a waitlist to book. That is a durable
-- business event, not an email feature — Gmail will later be a DELIVERY
-- MECHANISM attached to these records.
--
-- Why not just waitlist_entries.status = 'invited': a membership can
-- legitimately be invited more than once over its life (August, never
-- books; October, never books; January, books). One status + one
-- invited_at can only remember the most recent invitation, so every
-- earlier one — and the fact that this person has been asked three times —
-- would be silently overwritten. Same append-only shape as the existing
-- deal_stage_events / sales_call_events / enrollment_status_events tables.

CREATE TABLE IF NOT EXISTS "public"."waitlist_invitation_batches" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "offer_id" bigint NOT NULL,
    "cohort_id" bigint,
    "label" text,
    "status" text NOT NULL DEFAULT 'prepared',
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "waitlist_invitation_batches_status_check"
        CHECK (status IN ('prepared', 'sending', 'completed', 'cancelled')),
    CONSTRAINT "waitlist_invitation_batches_offer_id_fkey"
        FOREIGN KEY (offer_id) REFERENCES "public"."offers"(id),
    CONSTRAINT "waitlist_invitation_batches_cohort_id_fkey"
        FOREIGN KEY (cohort_id) REFERENCES "public"."cohorts"(id)
);

CREATE TABLE IF NOT EXISTS "public"."waitlist_invitations" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "batch_id" bigint NOT NULL,
    "waitlist_entry_id" bigint NOT NULL,
    "contact_id" bigint NOT NULL,
    "status" text NOT NULL DEFAULT 'prepared',
    "delivery_method" text,
    "prepared_at" timestamp with time zone NOT NULL DEFAULT now(),
    "sent_at" timestamp with time zone,
    "failed_at" timestamp with time zone,
    "failure_reason" text,
    "booked_sales_call_id" bigint,
    "booked_at" timestamp with time zone,
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "waitlist_invitations_status_check"
        CHECK (status IN ('prepared', 'sent', 'failed', 'cancelled')),
    CONSTRAINT "waitlist_invitations_delivery_method_check"
        CHECK (delivery_method IN ('manual', 'gmail')),
    -- Structural guarantee that nothing is ever marked delivered without
    -- real delivery evidence.
    CONSTRAINT "waitlist_invitations_sent_evidence_check"
        CHECK (status <> 'sent' OR (sent_at IS NOT NULL AND delivery_method IS NOT NULL)),
    CONSTRAINT "waitlist_invitations_batch_id_fkey"
        FOREIGN KEY (batch_id) REFERENCES "public"."waitlist_invitation_batches"(id),
    CONSTRAINT "waitlist_invitations_waitlist_entry_id_fkey"
        FOREIGN KEY (waitlist_entry_id) REFERENCES "public"."waitlist_entries"(id),
    CONSTRAINT "waitlist_invitations_contact_id_fkey"
        FOREIGN KEY (contact_id) REFERENCES "public"."contacts"(id),
    CONSTRAINT "waitlist_invitations_booked_sales_call_id_fkey"
        FOREIGN KEY (booked_sales_call_id) REFERENCES "public"."sales_calls"(id)
);

