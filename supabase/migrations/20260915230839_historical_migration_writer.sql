-- Re-issued HERE, after applications.contact_id exists, rather than earlier
-- in this file: the body writes applications(contact_id, ...), and although
-- plpgsql resolves column references at runtime (so an earlier definition
-- would still deploy), defining it before the column exists leaves a window
-- in which a live public application submission would fail. Ordering it
-- after the column removes that window entirely.
-- Phase 4J: submit_public_application() re-issued to stamp the two new
-- applications columns at live-intake write time (offer_id/intended_cohort_id
-- from the already-validated p_offer_id/p_cohort_id — never re-derived from
-- the Deal). Every other line is byte-identical to the current deployed body;
-- only the two lines around the INSERT changed (marked with a Phase 4J
-- comment) — see 02_functions.sql for the source of truth this mirrors.
CREATE OR REPLACE FUNCTION "public"."submit_public_application"(
    "p_offer_id" bigint,
    "p_cohort_id" bigint,
    "p_first_name" text,
    "p_last_name" text,
    "p_email" text,
    "p_phone" text,
    "p_answers" jsonb
) RETURNS jsonb
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_email text := lower(trim(p_email));
  v_contact contacts%ROWTYPE;
  v_is_dne boolean;
  v_deal deals%ROWTYPE;
  v_deal_reused boolean := false;
  v_pending_app applications%ROWTYPE;
  v_answers_match boolean := false;
  v_application_id bigint;
  v_existing_application_id bigint;
  v_sales_id bigint;
  v_has_pending_task boolean;
  v_applicant_name text;
BEGIN
  IF p_offer_id IS NULL THEN
    RAISE EXCEPTION 'offer_invalid' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  IF coalesce(trim(p_first_name), '') = '' OR coalesce(trim(p_last_name), '') = '' THEN
    RAISE EXCEPTION 'name_invalid' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  IF v_email = '' THEN
    RAISE EXCEPTION 'email_invalid' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM offers WHERE id = p_offer_id AND is_active) THEN
    RAISE EXCEPTION 'offer_invalid' USING ERRCODE = 'invalid_parameter_value';
  END IF;
  IF p_cohort_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM cohorts WHERE id = p_cohort_id AND offer_id = p_offer_id
  ) THEN
    RAISE EXCEPTION 'cohort_invalid' USING ERRCODE = 'invalid_parameter_value';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtext('submit_public_application:' || v_email));

  SELECT * INTO v_contact
  FROM contacts c
  WHERE EXISTS (
    SELECT 1 FROM jsonb_array_elements(coalesce(c.email_jsonb, '[]'::jsonb)) AS e
    WHERE lower(trim(e ->> 'email')) = v_email
  )
  ORDER BY c.id ASC
  LIMIT 1;

  v_is_dne := v_contact.id IS NOT NULL AND v_contact.sales_eligibility = 'do_not_engage';

  IF v_contact.id IS NOT NULL AND NOT v_is_dne THEN
    SELECT * INTO v_deal
    FROM deals d
    WHERE d.contact_id = v_contact.id
      AND d.offer_id = p_offer_id
      AND (p_cohort_id IS NULL OR d.cohort_id = p_cohort_id)
      AND d.archived_at IS NULL
      AND d.stage <> 'won'
      AND d.outcome IS NULL
    ORDER BY d.id ASC
    LIMIT 1;
  END IF;

  IF v_deal.id IS NOT NULL THEN
    SELECT * INTO v_pending_app
    FROM applications a
    WHERE a.opportunity_id = v_deal.id
    ORDER BY a.id DESC
    LIMIT 1;
    IF v_pending_app.id IS NOT NULL AND v_pending_app.status <> 'pending' THEN
      v_pending_app := NULL;
    END IF;
  END IF;

  IF v_pending_app.id IS NOT NULL THEN
    v_answers_match := p_answers = v_pending_app.raw_answers;
  END IF;

  IF v_contact.id IS NOT NULL AND NOT v_is_dne THEN
    SELECT EXISTS (
      SELECT 1 FROM tasks
      WHERE contact_id = v_contact.id
        AND type = 'review_application'
        AND done_date IS NULL
    ) INTO v_has_pending_task;
  END IF;

  IF v_pending_app.id IS NOT NULL AND v_answers_match AND coalesce(v_has_pending_task, false) THEN
    RETURN jsonb_build_object(
      'status', 'submitted',
      'application_id', v_pending_app.id,
      'dne_auto_resolved', false
    );
  END IF;

  IF v_contact.id IS NOT NULL THEN
    UPDATE contacts SET last_seen = now() WHERE id = v_contact.id RETURNING * INTO v_contact;
  ELSE
    INSERT INTO contacts (
      first_name, last_name, email_jsonb, phone_jsonb, tags,
      has_newsletter, first_seen, last_seen, sales_eligibility
    ) VALUES (
      p_first_name, p_last_name,
      jsonb_build_array(jsonb_build_object('email', p_email, 'type', 'Other')),
      CASE WHEN coalesce(p_phone, '') <> ''
        THEN jsonb_build_array(jsonb_build_object('number', p_phone, 'type', 'Other'))
        ELSE '[]'::jsonb
      END,
      ARRAY[]::bigint[],
      false, now(), now(), 'normal'
    ) RETURNING * INTO v_contact;
  END IF;

  IF v_deal.id IS NULL THEN
    INSERT INTO deals (
      contact_id, offer_id, cohort_id, stage, outcome, owner_decision,
      amount, entry_path, description
    ) VALUES (
      v_contact.id, p_offer_id, p_cohort_id, 'application_received',
      CASE WHEN v_is_dne THEN 'lost' ELSE NULL END,
      CASE WHEN v_is_dne THEN 'do_not_engage' ELSE NULL END,
      (SELECT current_price FROM offers WHERE id = p_offer_id),
      'application_form', ''
    ) RETURNING * INTO v_deal;
  ELSE
    v_deal_reused := true;
    IF NOT v_is_dne THEN
      UPDATE waitlist_entries
      SET status = 'converted', converted_at = now(), converted_opportunity_id = v_deal.id
      WHERE contact_id = v_deal.contact_id
        AND offer_id = v_deal.offer_id
        AND status IN ('waiting', 'invited')
        AND (cohort_id IS NULL OR cohort_id = v_deal.cohort_id);
    END IF;
  END IF;

  IF v_pending_app.id IS NOT NULL THEN
    UPDATE applications
    SET raw_answers = p_answers, submitted_at = now()
    WHERE id = v_pending_app.id
    RETURNING id INTO v_application_id;
  ELSE
    SELECT a.id INTO v_existing_application_id
    FROM applications a
    WHERE a.opportunity_id = v_deal.id
    ORDER BY a.id DESC
    LIMIT 1;

    IF v_existing_application_id IS NOT NULL THEN
      v_application_id := v_existing_application_id;
    ELSE
      -- Phase 4J: offer_id/intended_cohort_id stamped directly from the
      -- already-validated parameters, never re-derived from v_deal.
      -- Phase 4J: offer_id/intended_cohort_id stamped directly from the
      -- already-validated parameters, never re-derived from v_deal.
      -- Gate A final candidate: contact_id is the Application's canonical
      -- person relationship (the Deal remains the optional Opportunity
      -- relationship), and source marks this as a live submission that
      -- legitimately represents outstanding review work.
      INSERT INTO applications (contact_id, opportunity_id, offer_id, intended_cohort_id, raw_answers, submitted_at, status, reviewed_at, source)
      VALUES (
        v_contact.id, v_deal.id, p_offer_id, p_cohort_id, p_answers, now(),
        CASE WHEN v_is_dne THEN 'do_not_engage' ELSE 'pending' END,
        CASE WHEN v_is_dne THEN now() ELSE NULL END,
        'public_form'
      ) RETURNING id INTO v_application_id;
    END IF;
  END IF;

  IF NOT v_is_dne THEN
    SELECT EXISTS (
      SELECT 1 FROM tasks
      WHERE contact_id = v_contact.id
        AND type = 'review_application'
        AND done_date IS NULL
    ) INTO v_has_pending_task;

    IF NOT v_has_pending_task THEN
      SELECT id INTO v_sales_id FROM sales WHERE administrator = true LIMIT 1;
      v_applicant_name := trim(both ' ' from coalesce(v_contact.first_name, '') || ' ' || coalesce(v_contact.last_name, ''));
      INSERT INTO tasks (contact_id, type, text, due_date, status, sales_id)
      VALUES (
        v_contact.id, 'review_application',
        'Review ' || v_applicant_name || '''s application',
        now(), 'pending', v_sales_id
      );
    END IF;
  END IF;

  RETURN jsonb_build_object(
    'status', 'submitted',
    'application_id', v_application_id,
    'dne_auto_resolved', v_is_dne
  );
END;
$$;


-- ===========================================================================
-- Gate A final candidate: migration mode must not perform avatar HTTP
-- enrichment
-- ===========================================================================
-- handle_contact_saved() resolves a Contact avatar by calling gravatar.com
-- and then the email domain favicon service. That is an outbound request
-- per imported Contact during a bulk historical import, sending a hash of
-- each real client email address to a third party to decorate a back-filled
-- record. Guarded to skip ONLY that enrichment under migration mode.
-- Database-local contact invariants are unaffected: sales_id defaulting
-- (set_sales_id_default) and email lowercasing (lowercase_email_jsonb) are
-- separate triggers and continue to run. Normal live saves are unchanged.
CREATE OR REPLACE FUNCTION "public"."handle_contact_saved"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$declare contact_avatar text;
declare emails_length int8;
declare item jsonb;

begin
    if new.avatar is not null then
        return new;
    end if;

    -- Historical Migration slice: everything below this point is OUTBOUND
    -- HTTP enrichment — get_avatar_for_email() calls gravatar.com and then
    -- the email domain's favicon service. A bulk historical import fires
    -- one lookup per imported Contact, transmitting a hash of each real
    -- person's email address to third parties purely to decorate
    -- back-filled records (Gate A measured 271 such lookups). Migration
    -- mode skips the network enrichment ONLY: avatar is simply left null,
    -- to be filled by any later ordinary save. Every database-local
    -- contact invariant is untouched — sales_id defaulting and email
    -- lowercasing are their own separate triggers and still run. See
    -- set_historical_migration_mode()'s header for why this GUC is safe.
    if current_setting('app.migration_mode', true) = 'true' then
        return new;
    end if;

    select coalesce(jsonb_array_length(new.email_jsonb), 0) into emails_length;

    if emails_length = 0 then
        return new;
    end if;

    for item in select jsonb_array_elements(new.email_jsonb)
    loop
        select public.get_avatar_for_email(item->>'email') into contact_avatar;
        if (contact_avatar is not null) then
            exit;
        end if;
    end loop;

    if contact_avatar is null then
        return new;
    end if;

    new.avatar = concat('{"src":"', contact_avatar, '"}');
    return new;
end;$$;

-- ===========================================================================
-- Gate B: a no-showed sales call exits the Opportunity, atomically
-- ===========================================================================
-- Before this, completeSalesCallOutcome.ts's no_show branch deliberately
-- made NO Opportunity write, so a no-showed Deal sat at stage 'call_booked'
-- with outcome null — i.e. still in the active pipeline, indistinguishable
-- from a call that is still upcoming. A 'sales_call_no_show' Task existed
-- only to paper over that. Leif's rule: the no-show itself is certain
-- enough to exit the Opportunity, so the Deal leaves the pipeline and the
-- follow-up Task is no longer created.
--
-- One human action => one transaction. See the function body for why each
-- related change is represented the way it is.

CREATE OR REPLACE FUNCTION "public"."record_sales_call_no_show"("p_sales_call_id" bigint) RETURNS "jsonb"
    LANGUAGE "plpgsql"
    SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
declare
  v_call sales_calls%ROWTYPE;
  v_tag_id bigint;
  v_now timestamptz := now();
  v_deal_exited boolean := false;
begin
  -- Gate B: marking a sales call No-show is ONE human action, so it is one
  -- transaction. Every related state change below either all lands or none
  -- does: the CRM can never persist "Sales Call = no_show" while the
  -- Opportunity stays in the active pipeline, or exit the Opportunity
  -- without the Contact carrying the visible history — which is exactly
  -- what a sequence of independent UI writes could do if one failed.
  --
  -- Narrow by construction: this fires only when this function is called,
  -- never on arbitrary sales_calls UPDATEs, so ordinary edits/reschedules
  -- keep their existing behavior.
  select * into v_call from sales_calls where id = p_sales_call_id for update;
  if not found then
    return jsonb_build_object('status', 'not-found');
  end if;
  if v_call.opportunity_id is null then
    -- An unmatched booking has no Opportunity to exit yet.
    return jsonb_build_object('status', 'no-opportunity');
  end if;
  if v_call.attendance = 'attended' then
    -- Never silently overwrite a recorded attended outcome.
    return jsonb_build_object('status', 'already-completed');
  end if;

  -- 1. The Sales Call is the CANONICAL historical record of the no-show.
  --    status leaves 'booked' so the partial unique index
  --    (sales_calls_one_booked_per_opportunity_idx) does not block a later
  --    genuine rebooking.
  if v_call.attendance is distinct from 'no_show' then
    update sales_calls
       set attendance = 'no_show',
           attendance_recorded_at = v_now,
           status = 'completed',
           updated_at = v_now
     where id = v_call.id;

    insert into sales_call_events (sales_call_id, kind, occurred_at, attendance)
    values (v_call.id, 'attendance_recorded', v_now, 'no_show');
  elsif v_call.status <> 'completed' then
    -- Already recorded as a no-show but never concluded: a row written
    -- before a concluded call was required to leave 'booked'. Converge the
    -- status WITHOUT inventing a second attendance timestamp or a
    -- duplicate history event — the original attendance_recorded_at is the
    -- truth about when it was observed. Leaving it at 'booked' would keep
    -- blocking a genuine rebooking via the partial unique index.
    update sales_calls
       set status = 'completed',
           updated_at = v_now
     where id = v_call.id;
  end if;

  -- 2. The Opportunity exits the ACTIVE pipeline. "Active" is canonically
  --    archived_at is null AND stage <> 'won' AND outcome is null (see
  --    DealList.tsx's own filter), so setting outcome is the existing exit
  --    mechanism — no new stage, no new column, no Nurture. 'lost' is the
  --    same exit the Do-Not-Engage path already uses (deals/dneOutcome.ts);
  --    the REASON stays durable on the Sales Call itself (attendance =
  --    'no_show'), which is why no reason column is invented here.
  --    stage is deliberately NOT rewritten: the Deal genuinely reached
  --    Call Booked, and falsifying stage history to mark an exit would
  --    destroy that truth.
  update deals
     set outcome = 'lost',
         updated_at = v_now
   where id = v_call.opportunity_id
     and outcome is null
     and archived_at is null
     and stage <> 'won';
  v_deal_exited := found;

  -- 3. The Contact carries a durable, visible No-show tag — reusing the
  --    existing tags table + contacts.tags array, not a bespoke boolean.
  --    It is a SUMMARY for at-a-glance history, never the source of truth
  --    (that stays the Sales Call), and it is attached at most once.
  select id into v_tag_id from tags where lower(name) = 'no-show' limit 1;
  if v_tag_id is null then
    insert into tags (name, color) values ('No-show', '#fde2e4')
    returning id into v_tag_id;
  end if;

  update contacts
     set tags = coalesce(tags, '{}'::bigint[]) || v_tag_id
   where id = v_call.contact_id
     and not (coalesce(tags, '{}'::bigint[]) @> array[v_tag_id]);

  -- 4. Task lifecycle. The call concluded, so its "Sales Call" task is
  --    done. NO ordinary follow-up task is created: the Opportunity has
  --    left the pipeline, so there is no stranded work to re-surface —
  --    that visibility gap was the only reason the old
  --    'sales_call_no_show' task existed. Any such task still pending from
  --    before this rule is superseded work, so it is closed rather than
  --    left behind as impossible work.
  update tasks
     set done_date = v_now, status = 'completed'
   where contact_id = v_call.contact_id
     and type in ('sales_call', 'sales_call_no_show')
     and done_date is null;

  return jsonb_build_object(
    'status', case when v_call.attendance = 'no_show' then 'already-no-show' else 'completed' end,
    'sales_call_id', v_call.id,
    'opportunity_id', v_call.opportunity_id,
    'contact_id', v_call.contact_id,
    'deal_exited', v_deal_exited,
    'tag_id', v_tag_id
  );
end;
$$;

revoke all on function public.record_sales_call_no_show(bigint) from public;
grant execute on function public.record_sales_call_no_show(bigint) to authenticated;
grant execute on function public.record_sales_call_no_show(bigint) to service_role;

