-- Quantity per product and warehouse, only where there is stock
create or replace view public.stock_levels with (security_invoker = on) as
select
    l.product_id::text || '-' || l.warehouse_id::text as id,
    l.business_id,
    l.product_id,
    l.warehouse_id,
    p.unit_code,
    sum(l.quantity) as quantity
from (
    select m.business_id, m.product_id, m.to_warehouse_id as warehouse_id, m.quantity
    from public.stock_moves m
    where m.to_warehouse_id is not null
    union all
    select m.business_id, m.product_id, m.from_warehouse_id, -m.quantity
    from public.stock_moves m
    where m.from_warehouse_id is not null
) l
join public.products p on p.id = l.product_id
group by l.business_id, l.product_id, l.warehouse_id, p.unit_code
having sum(l.quantity) <> 0;

-- Products with their stock in all warehouses and their average cost: the
-- weighted average purchase cost of the receipts that were not reversed
create or replace view public.products_summary with (security_invoker = on) as
select
    p.id,
    p.business_id,
    p.created_at,
    p.kind,
    p.name,
    p.sku,
    p.unit_code,
    p.price,
    p.currency,
    p.vat_rate_code,
    p.barcodes,
    p.description,
    p.archived,
    coalesce((
        select sum(case when m.to_warehouse_id is not null and m.from_warehouse_id is null then m.quantity
                        when m.from_warehouse_id is not null and m.to_warehouse_id is null then -m.quantity
                        else 0 end)
        from public.stock_moves m
        where m.product_id = p.id
    ), 0) as quantity,
    (
        select round(sum(m.quantity * m.unit_cost) / nullif(sum(m.quantity), 0))::bigint
        from public.stock_moves m
        where m.product_id = p.id
          and m.kind = 'receipt'
          and not exists (select 1 from public.stock_moves r where r.reverses_id = m.id)
    ) as average_cost
from public.products p;

