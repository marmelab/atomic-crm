-- Owners, managers and storekeepers keep the catalog and post stock moves
CREATE OR REPLACE FUNCTION "public"."can_manage_stock"() RETURNS boolean
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO ''
    AS $$ select coalesce(public.current_business_role() in ('owner', 'manager', 'storekeeper'), false) $$;

-- Products: the business currency by default, barcodes trimmed and unique
-- within the business (SQLSTATE 23505, the barcode in the detail).
CREATE OR REPLACE FUNCTION "public"."check_product"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  taken text;
begin
  if new.currency is null then
    select b.currency into new.currency from public.businesses b where b.id = new.business_id;
  end if;
  new.sku := nullif(btrim(new.sku), '');
  new.barcodes := coalesce(array(
    select distinct btrim(code) from unnest(new.barcodes) as code where btrim(code) <> ''
  ), '{}');

  select code into taken
  from public.products p, unnest(p.barcodes) as code
  where p.business_id = new.business_id
    and p.id is distinct from new.id
    and code = any(new.barcodes)
  limit 1;
  if taken is not null then
    raise exception 'Barcode % belongs to another product', taken
      using errcode = '23505', detail = taken;
  end if;
  return new;
end;
$$;

-- Every business starts with its default warehouse
CREATE OR REPLACE FUNCTION "public"."create_default_warehouse"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  insert into public.warehouses (business_id, is_default) values (new.id, true);
  return new;
end;
$$;

-- Quantity of a product in a warehouse: the sum of its moves
CREATE OR REPLACE FUNCTION "public"."stock_quantity"("p_product_id" bigint, "p_warehouse_id" bigint) RETURNS numeric
    LANGUAGE "sql" STABLE
    SET "search_path" TO ''
    AS $$
    select coalesce(sum(case when m.to_warehouse_id = p_warehouse_id then m.quantity else -m.quantity end), 0)
    from public.stock_moves m
    where m.product_id = p_product_id
      and p_warehouse_id in (m.to_warehouse_id, m.from_warehouse_id)
$$;

-- Checks a new move: stock is kept for goods and materials only, a reversal
-- mirrors its move, and no warehouse goes below zero (SQLSTATE 23514).
CREATE OR REPLACE FUNCTION "public"."check_stock_move"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
  product public.products;
  original public.stock_moves;
  available numeric;
begin
  -- One move of a product at a time: the balance below cannot change meanwhile
  select * into product from public.products p
  where p.id = new.product_id and p.business_id = new.business_id
  for update;
  if product.kind = 'service' then
    raise exception 'A service has no stock' using errcode = '23514';
  end if;

  if new.currency is null then
    select b.currency into new.currency from public.businesses b where b.id = new.business_id;
  end if;
  new.created_by := auth.uid();

  if new.kind = 'reversal' then
    select * into original from public.stock_moves m
    where m.id = new.reverses_id and m.business_id = new.business_id;
    if not found or original.kind = 'reversal'
      or new.product_id <> original.product_id
      or new.quantity <> original.quantity
      or new.from_warehouse_id is distinct from original.to_warehouse_id
      or new.to_warehouse_id is distinct from original.from_warehouse_id then
      raise exception 'A reversal mirrors the move it cancels' using errcode = '23514';
    end if;
    new.unit_cost := original.unit_cost;
    new.currency := original.currency;
  end if;

  if new.from_warehouse_id is not null then
    available := public.stock_quantity(new.product_id, new.from_warehouse_id);
    if available < new.quantity then
      raise exception 'Not enough stock: % available', available
        using errcode = '23514', detail = available::text;
    end if;
  end if;

  return new;
end;
$$;

-- Posted moves are never changed or deleted, except with their whole business
CREATE OR REPLACE FUNCTION "public"."protect_stock_move"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  if tg_op = 'DELETE' and not exists (select 1 from public.businesses b where b.id = old.business_id) then
    return old;
  end if;
  raise exception 'A posted stock move cannot be changed: post a reversal instead'
    using errcode = '42501';
end;
$$;

-- Cancels a move by posting its mirror image; returns the id of the reversal
CREATE OR REPLACE FUNCTION "public"."reverse_stock_move"("p_move_id" bigint, "p_note" "text" DEFAULT NULL::"text") RETURNS bigint
    LANGUAGE "sql"
    SET "search_path" TO ''
    AS $$
    insert into public.stock_moves (kind, product_id, from_warehouse_id, to_warehouse_id, quantity, currency, counterparty_id, note, reverses_id)
    select 'reversal', m.product_id, m.to_warehouse_id, m.from_warehouse_id, m.quantity, m.currency, m.counterparty_id, p_note, m.id
    from public.stock_moves m
    where m.id = p_move_id
    returning id
$$;

-- Posts an inventory count of a warehouse: [{"product_id": 1, "quantity": 12}]
-- becomes one adjustment per product whose count differs from the stock.
-- Returns the number of adjustments posted.
CREATE OR REPLACE FUNCTION "public"."post_inventory"("p_warehouse_id" bigint, "p_counts" "jsonb", "p_note" "text" DEFAULT NULL::"text") RETURNS integer
    LANGUAGE "plpgsql"
    SET "search_path" TO ''
    AS $$
declare
  item record;
  difference numeric;
  posted integer := 0;
begin
  if jsonb_typeof(p_counts) <> 'array' then
    raise exception 'Counts are a list of {product_id, quantity}' using errcode = '22023';
  end if;
  for item in
    select (c ->> 'product_id')::bigint as product_id, (c ->> 'quantity')::numeric as quantity
    from jsonb_array_elements(p_counts) c
    order by 1
  loop
    if item.quantity is null or item.quantity < 0 then
      raise exception 'A counted quantity is zero or more' using errcode = '22023';
    end if;
    difference := item.quantity - public.stock_quantity(item.product_id, p_warehouse_id);
    if difference > 0 then
      insert into public.stock_moves (kind, product_id, to_warehouse_id, quantity, note)
      values ('adjustment', item.product_id, p_warehouse_id, difference, p_note);
      posted := posted + 1;
    elsif difference < 0 then
      insert into public.stock_moves (kind, product_id, from_warehouse_id, quantity, note)
      values ('adjustment', item.product_id, p_warehouse_id, -difference, p_note);
      posted := posted + 1;
    end if;
  end loop;
  return posted;
end;
$$;

