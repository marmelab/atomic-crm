-- Products, warehouses and stock moves (stages 2.3 and 2.4)
-- Same statements as supabase/schemas/14_products_stock.sql, plus the units
-- of measure and a default warehouse for every existing business.

--
-- Products and stock (TZ sections 5.6 and 9)
-- Products are goods, services or materials with a unit, barcodes and the
-- article numbers of their suppliers. Stock is never an editable number: it
-- is the sum of stock moves, and a posted move is never changed or deleted;
-- it is cancelled by a reversal that points to it.
-- Units of measure are reference data; their rows live in the migration.
--

create table public.units (
    code text not null primary key,
    -- English label; the interface translates crm.units.<code>
    label text not null,
    -- Decimal places a quantity may have (kilograms: 3, pieces: 0)
    decimals smallint not null default 0,
    sort_order smallint not null default 0,
    constraint units_code_format check (code ~ '^[a-z][a-z0-9_]*$'),
    constraint units_decimals check (decimals between 0 and 3)
);

create table public.products (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    kind text not null default 'goods',
    name text not null,
    sku text,
    unit_code text not null default 'pcs',
    -- Sale price in minor units of currency (the business currency by default)
    price bigint,
    currency text not null,
    -- Code of a VAT rate of the business country pack (tax_rates.code)
    vat_rate_code text,
    barcodes text[] not null default '{}'::text[],
    description text,
    archived boolean not null default false,
    constraint products_kind check (kind in ('goods', 'service', 'material')),
    constraint products_name_length check (length(btrim(name)) between 1 and 300),
    constraint products_price check (price >= 0),
    constraint products_currency_format check (currency ~ '^[A-Z]{3}$'),
    constraint products_id_business_id_key unique (id, business_id),
    constraint products_business_id_sku_key unique (business_id, sku)
);

-- Article numbers of a product at its suppliers
create table public.supplier_skus (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    product_id bigint not null,
    supplier_id bigint not null,
    sku text not null,
    constraint supplier_skus_sku_length check (length(btrim(sku)) between 1 and 100),
    constraint supplier_skus_business_id_supplier_id_sku_key unique (business_id, supplier_id, sku)
);

create table public.warehouses (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    -- Empty for the default warehouse: the interface names it in its language
    name text,
    is_default boolean not null default false,
    archived boolean not null default false,
    constraint warehouses_name_length check (name is null or length(btrim(name)) between 1 and 200),
    constraint warehouses_named check (is_default or name is not null),
    constraint warehouses_id_business_id_key unique (id, business_id)
);

-- A move of a quantity of a product into a warehouse (receipt), out of it
-- (issue), between two warehouses (transfer), a correction after counting
-- (adjustment, in or out) or the reversal of an earlier move.
create table public.stock_moves (
    id bigint generated by default as identity primary key,
    business_id uuid not null default public.current_business_id(),
    created_at timestamp with time zone not null default now(),
    created_by uuid default auth.uid(),
    moved_at timestamp with time zone not null default now(),
    kind text not null,
    product_id bigint not null,
    from_warehouse_id bigint,
    to_warehouse_id bigint,
    quantity numeric(14,3) not null,
    -- Purchase cost of one unit in minor units of currency (receipts)
    unit_cost bigint,
    currency text not null,
    counterparty_id bigint,
    note text,
    reverses_id bigint,
    constraint stock_moves_kind check (kind in ('receipt', 'issue', 'transfer', 'adjustment', 'reversal')),
    constraint stock_moves_quantity check (quantity > 0),
    constraint stock_moves_unit_cost check (unit_cost >= 0),
    constraint stock_moves_currency_format check (currency ~ '^[A-Z]{3}$'),
    constraint stock_moves_shape check (
        case kind
            when 'receipt' then to_warehouse_id is not null and from_warehouse_id is null and unit_cost is not null and reverses_id is null
            when 'issue' then from_warehouse_id is not null and to_warehouse_id is null and reverses_id is null
            when 'transfer' then from_warehouse_id is not null and to_warehouse_id is not null and from_warehouse_id <> to_warehouse_id and reverses_id is null
            when 'adjustment' then num_nonnulls(from_warehouse_id, to_warehouse_id) = 1 and reverses_id is null
            else reverses_id is not null and num_nonnulls(from_warehouse_id, to_warehouse_id) >= 1
        end
    ),
    constraint stock_moves_reverses_id_key unique (reverses_id),
    constraint stock_moves_id_business_id_key unique (id, business_id)
);

