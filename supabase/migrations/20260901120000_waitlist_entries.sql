CREATE TABLE "public"."waitlist_entries" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "contact_id" bigint NOT NULL,
    "offer_id" bigint NOT NULL,
    "cohort_id" bigint,
    "status" text NOT NULL DEFAULT 'waiting',
    "joined_at" timestamp with time zone NOT NULL DEFAULT now(),
    "desired_timing" text,
    "notes" text,
    "priority" smallint,
    "source" text,
    "invited_at" timestamp with time zone,
    "converted_at" timestamp with time zone,
    "converted_opportunity_id" bigint,
    "removed_at" timestamp with time zone,
    "created_at" timestamp with time zone NOT NULL DEFAULT now(),
    "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT "waitlist_entries_status_check" CHECK (status IN ('waiting', 'invited', 'converted', 'removed')),
    CONSTRAINT "waitlist_entries_source_check" CHECK (source IN ('instagram', 'referral', 'podcast', 'workshop', 'substack', 'google', 'other'))
);

ALTER TABLE "public"."waitlist_entries"
    ADD CONSTRAINT "waitlist_entries_contact_id_fkey" FOREIGN KEY (contact_id) REFERENCES public.contacts(id) ON UPDATE CASCADE ON DELETE CASCADE;

