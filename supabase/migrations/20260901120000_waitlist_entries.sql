-- Waitlists slice: a person can want access to a program without being in
-- the active sales pipeline. New standalone entity, not a Contact boolean
-- and not an Opportunity stage — see waitlist_entries table comment in
-- supabase/schemas/01_tables.sql for the full rationale.
--
-- Hand-authored (no local Postgres available in the session that wrote
-- this migration to run `supabase db diff`) — mirrors the declarative
-- schema changes in 01_tables.sql / 02_functions.sql / 04_triggers.sql /
-- 05_policies.sql exactly. Verify with `npx supabase db diff --local`
-- before trusting this file blindly in an environment where that's
