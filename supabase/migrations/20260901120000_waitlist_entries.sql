CREATE INDEX "waitlist_entries_contact_id_idx" ON public.waitlist_entries USING btree (contact_id);
CREATE INDEX "waitlist_entries_offer_id_idx" ON public.waitlist_entries USING btree (offer_id);
CREATE INDEX "waitlist_entries_cohort_id_idx" ON public.waitlist_entries USING btree (cohort_id);
CREATE INDEX "waitlist_entries_converted_opportunity_id_idx" ON public.waitlist_entries USING btree (converted_opportunity_id);

-- Prevents duplicate active (waiting/invited) entries for the same
-- Contact + Offer + Cohort — see the schema file comment for the
-- coalesce(-1) rationale (NULL cohort_id must collide with itself here).
CREATE UNIQUE INDEX "waitlist_entries_active_unique_idx" ON public.waitlist_entries (contact_id, offer_id, coalesce(cohort_id, -1)) WHERE (status IN ('waiting', 'invited'));

CREATE OR REPLACE FUNCTION "public"."handle_waitlist_entry_saved"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    SET "search_path" TO 'public'
    AS $$
declare
  v_offer offers%ROWTYPE;
  v_cohort_offer_id bigint;
begin
  select * into v_offer from offers where id = new.offer_id;
  if v_offer.id is null then
    raise exception 'Invalid offer_id %', new.offer_id;
  end if;

  if new.cohort_id is not null then
    select offer_id into v_cohort_offer_id from cohorts where id = new.cohort_id;
    if v_cohort_offer_id is null then
      raise exception 'Invalid cohort_id %', new.cohort_id;
    end if;
    if v_offer.type <> 'group' then
      raise exception 'cohort_id can only be set on a group offer (offer_id %)', new.offer_id;
    end if;
    if v_cohort_offer_id <> new.offer_id then
      raise exception 'cohort_id % does not belong to offer_id %', new.cohort_id, new.offer_id;
    end if;
  end if;

  return new;
end;
$$;

CREATE OR REPLACE TRIGGER "05_handle_waitlist_entry_saved"
    BEFORE INSERT OR UPDATE ON public.waitlist_entries
    FOR EACH ROW EXECUTE FUNCTION public.handle_waitlist_entry_saved();

